using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace ProcSense.EditorTools
{
    /// <summary>
    /// P3-AST-10: measures every prefab under Prefabs/Characters, Prefabs/Equipment and Prefabs/Environment (triangles, materials, largest texture and its Android format, LODs, skinned meshes) and writes
    /// docs/qa/asset_budgets.md. Run in batch: Unity.exe -batchmode -quit -projectPath unity -executeMethod ProcSense.EditorTools.AssetBudgetReport.Run
    /// The plans fix no per-asset limits (the acceptance is the headset frame time, P3-PRF-14), so this records measured numbers only; the heaviest prefabs come first in each group.
    /// </summary>
    public static class AssetBudgetReport
    {
        private static readonly string[] Groups = { "Prefabs/Characters", "Prefabs/Equipment", "Prefabs/Environment" };

        [MenuItem("ProcSense/Review/Write asset budget table")]
        public static void Run()
        {
            var sb = new StringBuilder();
            sb.AppendLine("# Asset budgets (P3-AST-10)").AppendLine();
            sb.AppendLine("Generated by `ProcSense.EditorTools.AssetBudgetReport.Run` (Editor, batch mode); do not edit by hand. Triangles are the sum over every mesh in the prefab (the first LOD when it has LODs); the texture column is the largest texture in the prefab's materials with its Android format. No per-asset limit is fixed in the plans: the acceptance is the headset frame time (P3-PRF-14), so these are the measured numbers to compare with it.").AppendLine();
            int total = 0;
            foreach (var group in Groups)
            {
                var rows = new List<(string name, int tris, int mats, string tex, int skinned, string lod)>();
                foreach (var guid in AssetDatabase.FindAssets("t:Prefab", new[] { "Assets/" + group }))
                {
                    var path = AssetDatabase.GUIDToAssetPath(guid);
                    var go = AssetDatabase.LoadAssetAtPath<GameObject>(path);
                    if (go == null) continue;
                    var lod = go.GetComponentInChildren<LODGroup>(true);
                    var rends = go.GetComponentsInChildren<Renderer>(true).ToList();
                    if (lod != null) { var l0 = lod.GetLODs(); if (l0.Length > 0) rends = l0[0].renderers.Where(r => r != null).ToList(); }
                    int tris = 0, skinned = 0;
                    foreach (var r in rends)
                    {
                        Mesh m = r is SkinnedMeshRenderer s ? s.sharedMesh : r.GetComponent<MeshFilter>()?.sharedMesh;
                        if (r is SkinnedMeshRenderer) skinned++;
                        if (m == null) continue;
                        for (int i = 0; i < m.subMeshCount; i++) tris += (int)(m.GetIndexCount(i) / 3);
                    }
                    var mats = rends.SelectMany(r => r.sharedMaterials).Where(m => m != null).Distinct().ToList();
                    int tex = 0; string fmt = "";
                    foreach (var mat in mats)
                        foreach (var name in mat.GetTexturePropertyNames())
                        {
                            var t = mat.GetTexture(name) as Texture2D; if (t == null) continue;
                            int size = Mathf.Max(t.width, t.height);
                            if (size > tex) { tex = size; fmt = AndroidFormat(AssetDatabase.GetAssetPath(t)); }
                        }
                    rows.Add((Path.GetFileNameWithoutExtension(path), tris, mats.Count, tex == 0 ? "none" : tex + " " + fmt, skinned, lod != null ? lod.lodCount.ToString() : "-"));
                }
                sb.AppendLine("## " + group).AppendLine();
                sb.AppendLine("| Prefab | Triangles | Materials | Largest texture | Skinned meshes | LODs |").AppendLine("|---|---|---|---|---|---|");
                foreach (var r in rows.OrderByDescending(r => r.tris)) sb.AppendLine("| " + r.name + " | " + r.tris + " | " + r.mats + " | " + r.tex + " | " + r.skinned + " | " + r.lod + " |");
                sb.AppendLine();
                total += rows.Count;
            }
            var file = Path.GetFullPath(Path.Combine(Application.dataPath, "../../docs/qa/asset_budgets.md"));
            File.WriteAllText(file, sb.ToString().Replace("\r\n", "\n"));
            Debug.Log("AssetBudgetReport: " + total + " prefabs measured, written to " + file);
        }

        private static string AndroidFormat(string path)
        {
            var imp = AssetImporter.GetAtPath(path) as TextureImporter;
            if (imp == null) return "";
            var s = imp.GetPlatformTextureSettings("Android");
            return s.overridden ? s.format.ToString() : "default";
        }
    }
}
