using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;

namespace ProcSense.EditorTools
{
    /// <summary>
    /// Quest texture budget (overhaul, 14 Nov 2026): Android-only maximum sizes by what a texture is for. The headset renders about 1440 x 1584 per eye and the GPU is saturated, so a 4096 floor or a 2048 prop
    /// map costs bandwidth for detail nobody can resolve. Rules only ever LOWER the effective Android size and keep an existing ASTC format (ASTC 6x6 is set where there is no override; normal maps ASTC 5x5). Never
    /// touched: anything that carries readable text (monitor, label, poster, sign, board, chart, screen, print, UI), characters (the character lane owns them), StreamingAssets, desktop import settings.
    /// Idempotent; writes docs/qa/quest_texture_budget.md. Batch: -executeMethod ProcSense.EditorTools.AndroidTextureBudget.Apply  (or .Preview for the report only).
    /// </summary>
    public static class AndroidTextureBudget
    {
        private static readonly Regex Protected = new Regex("monitor|label|poster|sign|board|chart|screen|print|/ui|ui_|text|font|welcome|ecg|record", RegexOptions.IgnoreCase);
        private static readonly Regex NormalMap = new Regex("normal|_n[.]|_nrm|bump", RegexOptions.IgnoreCase);
        private static readonly Regex DataMap = new Regex("rough|gloss|smooth|metal|_ao|ao_|occlusion|orm|height|mask", RegexOptions.IgnoreCase);

        // folder prefix, max size for colour maps, max size for data (roughness/AO/metal) maps, max size for normal maps
        private static readonly (string prefix, int colour, int data, int normal)[] Rules =
        {
            ("Assets/Textures/Hospital/PatientBayWood", 2048, 1024, 1024),
            ("Assets/Textures/Hospital/PBR", 1024, 512, 1024),
            ("Assets/Textures/Hospital/Corridor", 1024, 512, 1024),
            ("Assets/Textures/Hospital/FinalLook", 1024, 512, 1024),
            ("Assets/Textures/Hospital/PatientBayLook", 1024, 512, 1024),
            ("Assets/Textures/Hospital/Bed", 2048, 512, 1024),      // hero close-up (15 Nov 2026 sharpness pass): mattress cover 2048 ASTC 5x5, cover and pillow normals 1024 ASTC 4x4
            ("Assets/Textures/Environment/City", 512, 256, 256),
            ("Assets/Textures/Environment", 1024, 512, 512),
        };

        public static void Apply() => Run(true);
        public static void Preview() => Run(false);

        private static void Run(bool apply)
        {
            var sb = new StringBuilder("# Quest texture budget (generated)\n\n_Generated by `AndroidTextureBudget`. Android overrides only; desktop import settings untouched. Mpx = megapixels of the effective Android size (mip chain and compression excluded)._\n\n| Folder | Textures changed | Mpx before | Mpx after |\n|---|---|---|---|\n");
            var perFolder = new SortedDictionary<string, (int n, long before, long after)>();
            int changed = 0;
            foreach (var guid in AssetDatabase.FindAssets("t:Texture2D", new[] { "Assets/Textures" }))
            {
                var path = AssetDatabase.GUIDToAssetPath(guid);
                var rule = Rules.FirstOrDefault(r => path.StartsWith(r.prefix + "/")); if (rule.prefix == null) continue;
                if (Protected.IsMatch(path.Substring(rule.prefix.Length))) continue;
                var ti = AssetImporter.GetAtPath(path) as TextureImporter; if (ti == null || ti.textureType == TextureImporterType.Sprite || ti.textureType == TextureImporterType.GUI || ti.textureShape != TextureImporterShape.Texture2D) continue;
                string name = Path.GetFileNameWithoutExtension(path);
                bool normal = ti.textureType == TextureImporterType.NormalMap || NormalMap.IsMatch(name);
                bool colourName = Regex.IsMatch(name, "albedo|diffuse|color|colour|base", RegexOptions.IgnoreCase);
                int cap = normal ? rule.normal : (DataMap.IsMatch(name) && !colourName) ? rule.data : rule.colour;
                ti.GetSourceTextureWidthAndHeight(out int w, out int h);
                var a = ti.GetPlatformTextureSettings("Android");
                int before = Mathf.Min(Mathf.Max(w, h), a.overridden ? a.maxTextureSize : ti.maxTextureSize);
                int after = Mathf.Min(before, cap);
                if (!normal && colourName && cap > after && path.Contains("/PatientBayWood/")) after = Mathf.Min(Mathf.Max(w, h), cap);      // the big floor colour map that the first pass misfiled as a data map goes back up to its 2048 cap
                bool needFormat = !a.overridden || !IsAstc(a.format);
                if (after == before && !needFormat) { Add(perFolder, rule.prefix, 0, before, before); continue; }
                Add(perFolder, rule.prefix, 1, before, after);
                if (!apply) continue;
                var s = new TextureImporterPlatformSettings { name = "Android", overridden = true, maxTextureSize = after, textureCompression = TextureImporterCompression.Compressed, compressionQuality = 100,
                    format = IsAstc(a.format) && a.overridden ? a.format : normal ? TextureImporterFormat.ASTC_5x5 : TextureImporterFormat.ASTC_6x6, allowsAlphaSplitting = false };
                ti.SetPlatformTextureSettings(s); ti.SaveAndReimport(); changed++;
            }
            foreach (var kv in perFolder) sb.AppendLine("| `" + kv.Key + "` | " + kv.Value.n + " | " + (kv.Value.before / 1e6).ToString("F1") + " | " + (kv.Value.after / 1e6).ToString("F1") + " |");
            sb.AppendLine($"\nTextures rewritten: {changed}{(apply ? "" : " (preview, nothing written)")}. Protected from the rules: any path matching `{Protected}`.");
            File.WriteAllText("../docs/qa/quest_texture_budget.md", sb.ToString().Replace("\r\n", "\n"));
            Debug.Log("[AndroidTextureBudget] " + (apply ? "applied " : "preview ") + changed);
            EditorApplication.Exit(0);
        }

        private static bool IsAstc(TextureImporterFormat f) => f >= TextureImporterFormat.ASTC_4x4 && f <= TextureImporterFormat.ASTC_12x12;
        private static void Add(SortedDictionary<string, (int n, long before, long after)> d, string key, int n, int before, int after)
        { d.TryGetValue(key, out var v); d[key] = (v.n + n, v.before + (long)before * before, v.after + (long)after * after); }
    }
}
