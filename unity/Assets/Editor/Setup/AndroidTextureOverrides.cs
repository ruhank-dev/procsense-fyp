using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace ProcSense.EditorTools
{
    /// <summary>
    /// Quest texture memory (P3-17): the RenderConfigAudit found the patient-monitor textures stored uncompressed (2048 x 2048 RGBA, about 22 MB each with mipmaps, roughly 245 MB for the eleven)
    /// because no Android override existed. This sets an ASTC override for the Android platform only (desktop import settings are untouched), choosing the block size by what the map holds:
    /// 4x4 (8 bits per pixel, near-lossless) for the screen UI, label text and normal maps; 6x6 for ambient-occlusion, gloss and roughness data. Size stays 2048. Idempotent; writes
    /// docs/qa/quest2_texture_overrides.md. Batch: -executeMethod ProcSense.EditorTools.AndroidTextureOverrides.Apply (or .Revert to remove the overrides again).
    /// </summary>
    public static class AndroidTextureOverrides
    {
        private static readonly (string path, TextureImporterFormat format)[] Targets =
        {
            ("Assets/Textures/Hospital/Monitor/monitor_ui.png", TextureImporterFormat.ASTC_4x4),
            ("Assets/Textures/Hospital/Monitor/monitor_labels.png", TextureImporterFormat.ASTC_4x4),
            ("Assets/Textures/Hospital/Monitor/glass_normal.png", TextureImporterFormat.ASTC_4x4),
            ("Assets/Textures/Hospital/Monitor/plastic_orange_peel_n.png", TextureImporterFormat.ASTC_4x4),
            ("Assets/Textures/Hospital/Monitor/glass_gloss.png", TextureImporterFormat.ASTC_6x6),
            ("Assets/Textures/Hospital/Monitor/glass_smudge.png", TextureImporterFormat.ASTC_6x6),
            ("Assets/Textures/Hospital/Monitor/plastic_rough.png", TextureImporterFormat.ASTC_6x6),
            ("Assets/Textures/Hospital/Monitor/ao_Body.png", TextureImporterFormat.ASTC_6x6),
            ("Assets/Textures/Hospital/Monitor/ao_MonBezel.png", TextureImporterFormat.ASTC_6x6),
            ("Assets/Textures/Hospital/Monitor/ao_MonKey.png", TextureImporterFormat.ASTC_6x6),
            ("Assets/Textures/Hospital/Monitor/ao_MonShell2.png", TextureImporterFormat.ASTC_6x6),
        };

        public static void Apply() => Run(false);
        public static void Revert() => Run(true);

        /// <summary>Visual check on the desktop: gives the same textures the same ASTC format on the Standalone platform (Unity decodes ASTC in software there) so a capture shows exactly what the compressed texture looks like. PreviewOff removes it again.</summary>
        public static void PreviewOn() => Preview(true);
        public static void PreviewOff() => Preview(false);

        private static void Preview(bool on)
        {
            foreach (var (path, format) in Targets)
            {
                var ti = AssetImporter.GetAtPath(path) as TextureImporter; if (ti == null) continue;
                if (on) ti.SetPlatformTextureSettings(new TextureImporterPlatformSettings { name = "Standalone", overridden = true, maxTextureSize = ti.maxTextureSize, format = format, compressionQuality = 100, textureCompression = TextureImporterCompression.Compressed });
                else ti.ClearPlatformTextureSettings("Standalone");
                ti.SaveAndReimport();
            }
            Debug.Log("[AndroidTextureOverrides] preview " + (on ? "on" : "off")); EditorApplication.Exit(0);
        }

        private static void Run(bool revert)
        {
            var sb = new StringBuilder("# Android texture overrides (generated)\n\n_Generated by `AndroidTextureOverrides`. Android platform only; desktop import settings unchanged._\n\n| Texture | Before (Android) | After (Android) |\n|---|---|---|\n");
            foreach (var (path, format) in Targets)
            {
                var ti = AssetImporter.GetAtPath(path) as TextureImporter;
                if (ti == null) { sb.AppendLine($"| `{path}` | missing | - |"); continue; }
                var before = ti.GetPlatformTextureSettings("Android");
                string b = before.overridden ? $"{before.format} {before.maxTextureSize}" : $"no override ({ti.textureCompression}, {ti.maxTextureSize})";
                if (revert) { ti.ClearPlatformTextureSettings("Android"); }
                else
                {
                    var s = new TextureImporterPlatformSettings { name = "Android", overridden = true, maxTextureSize = ti.maxTextureSize, format = format, compressionQuality = 100, textureCompression = TextureImporterCompression.Compressed };
                    ti.SetPlatformTextureSettings(s);
                }
                ti.SaveAndReimport();
                var after = ti.GetPlatformTextureSettings("Android");
                sb.AppendLine($"| `{path}` | {b} | {(after.overridden ? after.format + " " + after.maxTextureSize : "no override")} |");
            }
            File.WriteAllText("../docs/qa/quest2_texture_overrides.md", sb.ToString().Replace("\r\n", "\n"));
            Debug.Log("[AndroidTextureOverrides] " + (revert ? "reverted" : "applied"));
            EditorApplication.Exit(0);
        }
    }
}
