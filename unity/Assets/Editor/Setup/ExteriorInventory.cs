using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

namespace ProcSense.EditorTools
{
    /// <summary>
    /// P3-EXT-02: inventory of every renderer under "City exterior" (and the bay's "Window exterior backdrop"): triangles, bounds, distance from the nearest hospital window, materials and shadow casting.
    /// Batch: -executeMethod ProcSense.EditorTools.ExteriorInventory.Run ; writes ../docs/qa/quest2_exterior_inventory.md. Read-only on the scenes.
    /// </summary>
    public static class ExteriorInventory
    {
        public static void Run()
        {
            var sb = new StringBuilder();
            sb.AppendLine("# Exterior city inventory (generated)").AppendLine();
            sb.AppendLine("_Generated by `ExteriorInventory`. Distance is from the corridor/bay window plane centre (x 4, y 1.6, z 2.2) to the nearest point of the renderer's bounds. Do not edit by hand._").AppendLine();
            sb.AppendLine("| Scene | Layer / object | Triangles | Verts | Materials | Casts shadows | Bounds min | Bounds max | Distance to hospital (m) |").AppendLine("|---|---|---|---|---|---|---|---|---|");
            var centre = new Vector3(4f, 1.6f, 2.2f);
            foreach (var path in new[] { "Assets/Scenes/PatientBay.unity", "Assets/Scenes/Corridor.unity" })
            {
                var scene = EditorSceneManager.OpenScene(path, OpenSceneMode.Single);
                int total = 0;
                foreach (var r in Object.FindObjectsByType<MeshRenderer>(FindObjectsInactive.Include, FindObjectsSortMode.None).OrderBy(x => x.name))
                {
                    bool city = false; for (var t = r.transform; t != null; t = t.parent) if (t.name == "City exterior" || t.name == "Window exterior backdrop") city = true;
                    if (!city) continue;
                    var mf = r.GetComponent<MeshFilter>(); if (mf == null || mf.sharedMesh == null) continue;
                    int tris = 0; for (int s = 0; s < mf.sharedMesh.subMeshCount; s++) tris += (int)(mf.sharedMesh.GetIndexCount(s) / 3);
                    total += tris; var b = r.bounds; float d = Mathf.Sqrt(b.SqrDistance(centre));
                    string parent = r.transform.parent != null ? r.transform.parent.name + "/" : "";
                    sb.AppendLine($"| {scene.name} | {parent}{r.name} | {tris:N0} | {mf.sharedMesh.vertexCount:N0} | {string.Join(", ", r.sharedMaterials.Select(m => m != null ? m.name : "null"))} | {r.shadowCastingMode} | {b.min:F0} | {b.max:F0} | {d:F0} |");
                }
                sb.AppendLine($"| {scene.name} | **total** | **{total:N0}** | | | | | | |");
            }
            File.WriteAllText("../docs/qa/quest2_exterior_inventory.md", sb.ToString().Replace("\r\n", "\n"));
            EditorApplication.Exit(0);
        }
    }
}
