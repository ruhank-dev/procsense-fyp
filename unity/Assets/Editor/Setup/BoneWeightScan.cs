using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

namespace ProcSense.EditorTools
{
    /// <summary>
    /// DT-282: finds the skinned mesh behind the Editor message "First two bone weights should have non-zero sum". Scans every skinned mesh used by the three room scenes (and every model/prefab
    /// under Assets/) for vertices whose first two bone weights sum to zero, and lists the asset, the vertex count and the owners. Read-only. Batch: -executeMethod ProcSense.EditorTools.BoneWeightScan.Run
    /// </summary>
    public static class BoneWeightScan
    {
        public static void Run()
        {
            var sb = new StringBuilder("# Skinned-mesh bone-weight scan (generated)\n\n_Vertices whose first two bone weights sum to zero (including vertices with no bone at all). Generated by `BoneWeightScan`; do not edit by hand._\n\n| Source | Mesh | Vertices | Bad vertices | Bones per vertex (min-max) |\n|---|---|---|---|---|\n");
            int bad = 0, seen = 0;
            void Check(string source, SkinnedMeshRenderer r)
            {
                var m = r.sharedMesh; if (m == null) return; seen++;
                var bpv = m.GetBonesPerVertex(); var all = m.GetAllBoneWeights(); int badV = 0, idx = 0, min = int.MaxValue, max = 0;
                if (bpv.Length == 0 && m.vertexCount > 0) { bad++; sb.AppendLine($"| {source} | {m.name} ({AssetDatabase.GetAssetPath(m)}) | {m.vertexCount} | {m.vertexCount} | no weights at all |"); return; }
                for (int v = 0; v < bpv.Length; v++)
                {
                    int n = bpv[v]; min = Mathf.Min(min, n); max = Mathf.Max(max, n);
                    float w0 = n > 0 ? all[idx].weight : 0f, w1 = n > 1 ? all[idx + 1].weight : 0f;
                    if (n == 0 || w0 + w1 <= 0f) badV++;
                    idx += n;
                }
                if (badV > 0) { bad++; sb.AppendLine($"| {source} | {m.name} ({AssetDatabase.GetAssetPath(m)}) | {bpv.Length} | {badV} | {min}-{max} |"); }
            }
            foreach (var guid in AssetDatabase.FindAssets("t:Scene", new[] { "Assets/Scenes" }))
            {
                var path = AssetDatabase.GUIDToAssetPath(guid); var scene = EditorSceneManager.OpenScene(path, OpenSceneMode.Single);
                foreach (var r in Object.FindObjectsByType<SkinnedMeshRenderer>(FindObjectsInactive.Include, FindObjectsSortMode.None)) Check(scene.name + ":" + r.name, r);
            }
            foreach (var guid in AssetDatabase.FindAssets("t:Prefab", new[] { "Assets" }).Concat(AssetDatabase.FindAssets("t:Model", new[] { "Assets" })))
            {
                var path = AssetDatabase.GUIDToAssetPath(guid); var go = AssetDatabase.LoadAssetAtPath<GameObject>(path); if (go == null) continue;
                foreach (var r in go.GetComponentsInChildren<SkinnedMeshRenderer>(true)) Check(path + ":" + r.name, r);
            }
            sb.AppendLine($"\nSkinned meshes checked: {seen}; with a bad vertex: {bad}.");
            File.WriteAllText("../docs/qa/skinned_bone_weight_scan.md", sb.ToString().Replace("\r\n", "\n"));
            Debug.Log("[BoneWeightScan] checked " + seen + ", bad " + bad);
            EditorApplication.Exit(0);
        }
    }
}
