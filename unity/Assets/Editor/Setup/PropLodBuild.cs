using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

namespace ProcSense.EditorTools
{
    /// <summary>
    /// Prop LODs for the Quest (overhaul, 14 Nov 2026). The Quest GPU is saturated, so heavy static props get two cheaper levels chosen by projected SCREEN HEIGHT (not distance): LOD1 about 45% and LOD2
    /// about 15% of the triangles (vertex-clustering simplification, per submesh, so materials stay intact; seams average their UVs, which is invisible at the sizes where these levels show), then culled below
    /// 1.5% of the screen height. Skinned meshes (characters, curtains) belong to the character lane. Lightmapped renderers are left alone (a level without matching lightmap UVs would light differently).
    /// Re-runnable; never deletes; the simplified meshes are assets under Assets/Models/Environment/Lod. Writes docs/qa/quest_prop_lods.md.
    /// Batch: -executeMethod ProcSense.EditorTools.PropLodBuild.Run
    /// </summary>
    public static class PropLodBuild
    {
        private const int MinTriangles = 2500;
        private const string Dir = "Assets/Models/Environment/Lod";
        private static readonly string[] Scenes = { "PatientBay", "Corridor", "OT" };
        private static readonly float[] Keep = { 0.45f, 0.15f };
        private static readonly float[] Transitions = { 0.22f, 0.07f, 0.015f };       // screen height at which LOD1, LOD2 and culling start

        public static void Run()
        {
            bool ok = false;
            try { Build(); ok = true; } catch (Exception e) { Debug.LogError("[PropLodBuild] " + e); }
            EditorApplication.Exit(ok ? 0 : 1);
        }

        private static void Build()
        {
            Directory.CreateDirectory(Dir);
            var report = new StringBuilder("# Quest prop LODs (generated)\n\n_Generated by `PropLodBuild`. LOD1/LOD2 keep about 45% / 15% of the triangles; levels switch at 22% / 7% of the screen height and the object is culled below 1.5%._\n\n| Scene | Object | Mesh | Triangles L0 / L1 / L2 |\n|---|---|---|---|\n");
            var meshCache = new Dictionary<(Mesh, int), Mesh>(); int groups = 0; int skippedUnreadable = 0, skippedLightmapped = 0;
            foreach (var sceneName in Scenes)
            {
                var scene = EditorSceneManager.OpenScene("Assets/Scenes/" + sceneName + ".unity", OpenSceneMode.Single);
                bool dirty = false;
                foreach (var r in UnityEngine.Object.FindObjectsByType<MeshRenderer>(FindObjectsInactive.Exclude, FindObjectsSortMode.None))
                {
                    var mf = r.GetComponent<MeshFilter>(); if (mf == null || mf.sharedMesh == null) continue;
                    var mesh = mf.sharedMesh; if (Tris(mesh) < MinTriangles) continue;
                    if (r.GetComponentInParent<LODGroup>() != null) continue;
                    if (IsCityOrSky(r.transform)) continue;
                    if (r.lightmapIndex >= 0 && r.lightmapIndex < 65534) { skippedLightmapped++; continue; }
                    if (r.sharedMaterials.Any(m => m != null && m.shader != null && m.shader.name.StartsWith("ProcSense/Sun"))) continue;
                    if (!mesh.isReadable) { skippedUnreadable++; continue; }
                    var l1 = Simplified(mesh, 0, meshCache); var l2 = Simplified(mesh, 1, meshCache); if (l1 == null || l2 == null) continue;
                    var go = r.gameObject;
                    var lods = new LOD[3];
                    lods[0] = new LOD(Transitions[0], new Renderer[] { r });
                    lods[1] = new LOD(Transitions[1], new Renderer[] { Level(r, l1, "LOD1") });
                    lods[2] = new LOD(Transitions[2], new Renderer[] { Level(r, l2, "LOD2") });
                    var group = go.AddComponent<LODGroup>(); group.SetLODs(lods); group.fadeMode = LODFadeMode.None; group.RecalculateBounds();
                    groups++; dirty = true;
                    report.AppendLine("| " + sceneName + " | " + go.name + " | " + mesh.name + " | " + Tris(mesh).ToString("N0") + " / " + Tris(l1).ToString("N0") + " / " + Tris(l2).ToString("N0") + " |");
                }
                if (dirty) { EditorSceneManager.MarkSceneDirty(scene); EditorSceneManager.SaveScene(scene); }
            }
            report.AppendLine("\nLOD groups added: " + groups + ". Left alone: " + skippedLightmapped + " lightmapped renderers over " + MinTriangles + " triangles (their lighting is baked), " + skippedUnreadable + " unreadable meshes (Read/Write off).");
            File.WriteAllText("../docs/qa/quest_prop_lods.md", report.ToString().Replace("\r\n", "\n"));
            AssetDatabase.SaveAssets();
            Debug.Log("[PropLodBuild] groups " + groups + ", lightmapped skipped " + skippedLightmapped + ", unreadable skipped " + skippedUnreadable);
        }

        private static bool IsCityOrSky(Transform t) { for (; t != null; t = t.parent) if (t.name.StartsWith("City exterior") || t.name.StartsWith("Skyline") || t.name.StartsWith("Layer C")) return true; return false; }

        private static Renderer Level(MeshRenderer src, Mesh mesh, string name)
        {
            var go = new GameObject(src.gameObject.name + " " + name); go.transform.SetParent(src.transform, false); go.layer = src.gameObject.layer;
            go.AddComponent<MeshFilter>().sharedMesh = mesh;
            var r = go.AddComponent<MeshRenderer>(); r.sharedMaterials = src.sharedMaterials; r.shadowCastingMode = src.shadowCastingMode; r.receiveShadows = src.receiveShadows;
            r.lightProbeUsage = src.lightProbeUsage; r.reflectionProbeUsage = src.reflectionProbeUsage; r.renderingLayerMask = src.renderingLayerMask; r.motionVectorGenerationMode = src.motionVectorGenerationMode;
            GameObjectUtility.SetStaticEditorFlags(go, GameObjectUtility.GetStaticEditorFlags(src.gameObject));
            return r;
        }

        private static int Tris(Mesh m) { int t = 0; for (int s = 0; s < m.subMeshCount; s++) t += (int)m.GetIndexCount(s) / 3; return t; }

        private static Mesh Simplified(Mesh src, int level, Dictionary<(Mesh, int), Mesh> cache)
        {
            if (cache.TryGetValue((src, level), out var m)) return m;
            var path = Dir + "/" + Safe(src.name) + "_lod" + (level + 1) + ".asset";
            var existing = AssetDatabase.LoadAssetAtPath<Mesh>(path); if (existing != null) return cache[(src, level)] = existing;
            int target = Mathf.Max(60, Mathf.RoundToInt(Tris(src) * Keep[level]));
            var b = src.bounds; float lo = Mathf.Max(b.size.magnitude / 4000f, 1e-4f), hi = b.size.magnitude / 2f; Mesh best = null;
            for (int it = 0; it < 14; it++)
            {
                float cell = (lo + hi) * 0.5f; var cand = Cluster(src, cell);
                if (Tris(cand) > target) lo = cell; else { hi = cell; best = cand; }
            }
            if (best == null) best = Cluster(src, hi);
            best.name = src.name + "_lod" + (level + 1);
            best.RecalculateBounds(); best.UploadMeshData(false);
            AssetDatabase.CreateAsset(best, path);
            return cache[(src, level)] = best;
        }

        private static string Safe(string n) => string.Concat(n.Select(c => char.IsLetterOrDigit(c) || c == '_' || c == '-' ? c : '_'));

        // Vertex clustering: vertices within one grid cell merge into one (positions, normals and UVs averaged); degenerate triangles disappear; submeshes (materials) are kept.
        private static Mesh Cluster(Mesh src, float cell)
        {
            var v = src.vertices; var n = src.normals; var uv = src.uv; bool hasN = n.Length == v.Length, hasUv = uv.Length == v.Length;
            var map = new int[v.Length]; var keys = new Dictionary<(int, int, int), int>(); var pos = new List<Vector3>(); var nor = new List<Vector3>(); var uvs = new List<Vector2>(); var cnt = new List<int>();
            for (int i = 0; i < v.Length; i++)
            {
                var k = (Mathf.FloorToInt(v[i].x / cell), Mathf.FloorToInt(v[i].y / cell), Mathf.FloorToInt(v[i].z / cell));
                if (!keys.TryGetValue(k, out int id)) { id = pos.Count; keys[k] = id; pos.Add(Vector3.zero); nor.Add(Vector3.zero); uvs.Add(Vector2.zero); cnt.Add(0); }
                pos[id] += v[i]; if (hasN) nor[id] += n[i]; if (hasUv) uvs[id] += uv[i]; cnt[id]++; map[i] = id;
            }
            var res = new Mesh { indexFormat = pos.Count > 65000 ? UnityEngine.Rendering.IndexFormat.UInt32 : UnityEngine.Rendering.IndexFormat.UInt16 };
            res.SetVertices(pos.Select((p, i) => p / cnt[i]).ToList());
            if (hasN) res.SetNormals(nor.Select(x => x.sqrMagnitude > 1e-8f ? x.normalized : Vector3.up).ToList());
            if (hasUv) res.SetUVs(0, uvs.Select((u, i) => u / cnt[i]).ToList());
            res.subMeshCount = src.subMeshCount;
            for (int s = 0; s < src.subMeshCount; s++)
            {
                var idx = src.GetIndices(s); var tri = new List<int>();
                for (int i = 0; i + 2 < idx.Length; i += 3) { int a = map[idx[i]], b2 = map[idx[i + 1]], c = map[idx[i + 2]]; if (a != b2 && b2 != c && a != c) { tri.Add(a); tri.Add(b2); tri.Add(c); } }
                res.SetTriangles(tri, s);
            }
            if (!hasN) res.RecalculateNormals();
            res.RecalculateTangents();
            return res;
        }
    }
}
