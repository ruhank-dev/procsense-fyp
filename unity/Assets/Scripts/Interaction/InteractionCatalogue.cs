using System.Collections.Generic;
using System.Linq;
using ProcSense.Core.Content;
using ProcSense.VR.Content;

namespace ProcSense.VR.Interaction
{
    /// <summary>One action of the catalogue: the tablet entry it is (tab, verb, parameters, label), its icon, whether it needs a confirmation, whether it opens a form, and what a trainee may say for it.</summary>
    public sealed class CatalogueEntry
    {
        public string Id = "", Tab = "", Verb = "", Label = "", Icon = "";
        public bool Confirm, HasForm, Spoken;
        public readonly SortedDictionary<string, string> Params = new SortedDictionary<string, string>(System.StringComparer.Ordinal);
        public readonly List<string> VoiceExamples = new List<string>();
    }

    public sealed class CatalogueGroup
    {
        public string Id = "", Label = "";
        public readonly List<string> Entries = new List<string>();
    }

    public sealed class CatalogueEntity
    {
        public string Id = "", Label = "";
        public readonly List<CatalogueGroup> Groups = new List<CatalogueGroup>();
    }

    /// <summary>
    /// content/ui/interactions.json (P3-CTX-01, generated by tools/content/build_interactions.py from the tablet): each entity type's groups of tablet entries, and per entry its icon, confirmation
    /// flag, form flag and voice examples. Read-only; Unity adds no clinical rule.
    /// </summary>
    public sealed class InteractionCatalogue
    {
        public const string File = "ui/interactions.json";
        public readonly Dictionary<string, CatalogueEntity> Entities = new Dictionary<string, CatalogueEntity>();
        public readonly Dictionary<string, CatalogueEntry> Entries = new Dictionary<string, CatalogueEntry>();
        public readonly List<string> Global = new List<string>();
        /// <summary>P3-VOX-04: the reference card's extra examples per entity type (content/ui/voice_examples.json), used after the catalogue's own spoken entries.</summary>
        public readonly Dictionary<string, List<string>> VoiceExamples = new Dictionary<string, List<string>>();
        public const string ExamplesFile = "ui/voice_examples.json";

        /// <summary>Reads the extra examples; a missing file leaves the catalogue's own.</summary>
        public InteractionCatalogue WithExamples(string json)
        {
            if (string.IsNullOrEmpty(json)) return this;
            if (MiniJson.Parse(json) is Dictionary<string, object> root && root.TryGetValue("entities", out var e) && e is Dictionary<string, object> map)
                foreach (var kv in map) if (kv.Value is List<object> list) VoiceExamples[kv.Key] = list.Select(x => (string)x).ToList();
            return this;
        }

        private static InteractionCatalogue _current;
        public static InteractionCatalogue Current
        {
            get
            {
                if (_current != null) return _current;
                var reader = UnityContentReader.ForThisPlatform();
                string examples = null;
                try { examples = reader.ReadText(ExamplesFile); } catch (System.Exception) { }
                return _current = Parse(reader.ReadText(File)).WithExamples(examples);
            }
        }

        public IEnumerable<CatalogueEntry> EntriesOf(string entityType) =>
            Entities.TryGetValue(entityType ?? "", out var e) ? e.Groups.SelectMany(g => g.Entries).Where(Entries.ContainsKey).Select(id => Entries[id]) : Enumerable.Empty<CatalogueEntry>();

        public static InteractionCatalogue Parse(string json)
        {
            var root = MiniJson.Parse(json) as Dictionary<string, object> ?? throw new ContentException(File + ": expected an object");
            var c = new InteractionCatalogue();
            foreach (Dictionary<string, object> e in (List<object>)root["entities"])
            {
                var entity = new CatalogueEntity { Id = (string)e["id"], Label = (string)e["label"] };
                foreach (Dictionary<string, object> g in (List<object>)e["groups"])
                {
                    var group = new CatalogueGroup { Id = (string)g["id"], Label = (string)g["label"] };
                    foreach (var id in (List<object>)g["entries"]) group.Entries.Add((string)id);
                    entity.Groups.Add(group);
                }
                c.Entities[entity.Id] = entity;
            }
            foreach (Dictionary<string, object> x in (List<object>)root["entries"])
            {
                var entry = new CatalogueEntry
                {
                    Id = (string)x["id"], Tab = (string)x["tab"], Verb = (string)x["verb"], Label = (string)x["label"], Icon = x.TryGetValue("icon", out var i) ? i as string ?? "" : "",
                    Confirm = x.TryGetValue("confirm", out var cf) && cf is bool b1 && b1, HasForm = x.TryGetValue("has_form", out var hf) && hf is bool b2 && b2,
                };
                if (x.TryGetValue("params", out var p) && p is Dictionary<string, object> ps) foreach (var kv in ps) entry.Params[kv.Key] = kv.Value as string ?? "";
                if (x.TryGetValue("voice", out var v) && v is Dictionary<string, object> voice)
                {
                    entry.Spoken = voice.TryGetValue("spoken", out var s) && s is bool b3 && b3;
                    if (voice.TryGetValue("examples", out var ex) && ex is List<object> list) foreach (var t in list) entry.VoiceExamples.Add((string)t);
                }
                c.Entries[entry.Id] = entry;
            }
            if (root.TryGetValue("global", out var gl) && gl is Dictionary<string, object> global && global.TryGetValue("entries", out var ge) && ge is List<object> gl2)
                foreach (var id in gl2) c.Global.Add((string)id);
            return c;
        }
    }
}
