"""The single source of truth for everything that needs Sannan or another outside actor (`docs/testing/external_testing.json` -> `docs/testing/SANNAN_EXTERNAL_TESTING.md`): `uv run --project tools tools/plans/external_testing.py [--check | --link-steps]`.

The page lists, with exact steps, pass rules and evidence, every headset check (DC-), every Unity, 3D or VR acceptance group of the P0 plan (UX-) and every item that needs other people, accounts, permissions or the owner (EX-). The tool refuses to
run, and CI fails, when: an id is repeated; an item names a step or a prepared file that does not exist; a step whose reconciliation says an outside actor is still needed (engineering done with an external gate, partly done, blocked, or
owned by Sannan and not yet approved) is in no item; or the committed page differs from what the data and the result files give. The status of an item is read from `docs/testing/results/<ID>.md` (`Result: PASS | FAIL | NOT RUN`);
no result file means NOT RUN. Nothing here is a result. Standard library only.
"""
from __future__ import annotations

import glob
import json
import os
import re
import subprocess
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "docs" / "testing" / "external_testing.json"
RECON = ROOT / "docs" / "plans" / "reconciliation.json"
PIPELINE = ROOT / "docs" / "architecture" / "procsense_full_pipeline.json"
RESULTS = ROOT / "docs" / "testing" / "results"
PAGE = ROOT / "docs" / "testing" / "SANNAN_EXTERNAL_TESTING.md"
WHY = {
    "device": "It needs a headset, a Unity build or a particular machine, which the desktop checks and GitHub Actions do not have.",
    "unity": "It needs the Unity Editor or a Quest: the engine half is covered by tests, the scene, prop or screen half is not.",
    "people": "It needs people's judgement, labelling or consent. No machine check can stand in for it, and an AI judge or a simulation is not human validation.",
    "account": "Only the account holder can read and accept the terms; nobody else may accept for them.",
    "permission": "Only the licensor or the person entitled to grant the permission can give it.",
    "owner": "It is the owner's decision or authoring work; no check can make it.",
}
NEED_EXTERNAL = {"ENG_DONE", "PARTLY", "BLOCKED", "DONE_GATE_OFF"}


def step_files() -> dict[str, dict]:
    out = {}
    for f in sorted(glob.glob(str(ROOT / "docs" / "plans" / "p[012]" / "*" / "steps" / "*.md"))):
        name = os.path.basename(f)
        sid = re.match(r"(.+?-s\d{2})", name.replace("✅ ", "")).group(1)
        text = Path(f).read_text(encoding="utf-8")
        ver = re.search(r"## Verification\n(.*?)(?=\n## |\Z)", text, re.S)
        how = re.search(r"## How to implement\n(.*?)(?=\n## |\Z)", text, re.S)
        out[sid] = {"file": Path(f).relative_to(ROOT / "docs").as_posix(), "title": text.splitlines()[0].lstrip("# ").split(" — ", 1)[-1], "ticked": name.startswith("✅"),
                    "verification": re.sub(r"\s+", " ", ver.group(1)).strip() if ver else "", "how": how.group(1).strip() if how else ""}
    return out


def features_of(steps: list[str]) -> list[str]:
    nodes = json.loads(PIPELINE.read_text(encoding="utf-8"))["nodes"]
    return sorted({n["id"] for n in nodes if n["type"] == "feature" and set(n.get("tasks", [])) & set(steps)}, key=lambda x: (x[0], int(re.sub(r"\D", "", x))))


START, END = "<!-- external-testing:start (generated by tools/plans/external_testing.py) -->", "<!-- external-testing:end -->"


def link_block(sid: str, steps: dict[str, dict], items: list[dict]) -> str:
    """The generated section at the end of a step file that points to the items closing it (idempotent; the page is the single source of truth)."""
    mine = [i for i in items if sid in i["steps"]]
    if not mine:
        return ""
    rel = os.path.relpath(ROOT / "docs" / "testing" / "SANNAN_EXTERNAL_TESTING.md", (ROOT / "docs" / steps[sid]["file"]).parent).replace(os.sep, "/")
    lines = [START, "## External acceptance", "", "This step has acceptance that only a person, device or account outside the engineering desk can give. The exact procedure, pass rule and evidence are in the single source of truth:", ""]
    lines += [f"* [{i['id']}]({rel}#{i['id'].lower()}): {i['title']}" for i in mine]
    lines += ["", END]
    return "\n".join(lines)


def with_block(text: str, block: str) -> str:
    base = text.split(START)[0].rstrip("\n") if START in text else text.rstrip("\n")
    return (base + "\n\n" + block + "\n") if block else base + "\n"


def result_of(item_id: str) -> tuple[str, str]:
    p = RESULTS / f"{item_id}.md"
    if not p.exists():
        return "NOT RUN", ""
    text = p.read_text(encoding="utf-8")
    m = re.search(r"^Result:\s*(PASS|FAIL|NOT RUN)\b", text, re.M | re.I)
    return (m.group(1).upper() if m else "NOT RUN"), f"docs/testing/results/{item_id}.md"


def all_items(data: dict) -> list[dict]:
    return [dict(i, group="device") for i in data["device_checks"]] + [dict(i, group="unity", kind="unity") for i in data["unity_groups"]] + [dict(i, group="other") for i in data["other_items"]]


def git_ignored(rel: str) -> bool:
    """True when git ignores the path: a generated output, not a file the repository holds."""
    return subprocess.run(["git", "check-ignore", "-q", "--no-index", rel], cwd=ROOT).returncode == 0


def problems(data: dict, recon: dict, steps: dict[str, dict]) -> list[str]:
    out = []
    items = all_items(data)
    ids = [i["id"] for i in items]
    out += [f"duplicate id {i}" for i in sorted({x for x in ids if ids.count(x) > 1})]
    covered = set()
    for it in items:
        for s in it["steps"]:
            covered.add(s)
            if s not in steps:
                out.append(f"{it['id']}: {s} is not a step")
        for p in it.get("prepared", []):
            if not (ROOT / p).exists() and not git_ignored(p):   # a git-ignored output (such as build/voice) is made by a task on the tester's machine, so a clone cannot have it
                out.append(f"{it['id']}: prepared file {p} does not exist")
        for key in (("title", "needs", "pass_rule") if it["group"] != "unity" else ("title", "needs", "who")):
            if not it.get(key):
                out.append(f"{it['id']}: no {key}")
        if it["group"] in ("device", "other") and not (it.get("procedure") and it.get("after")):
            out.append(f"{it['id']}: needs a procedure and what happens after it passes")
        if it["group"] == "other" and (not it.get("who") or it.get("kind") not in WHY):
            out.append(f"{it['id']}: needs `who` and a kind of {sorted(WHY)}")
    for sid, e in recon["steps"].items():
        if sid not in steps:
            continue
        needs = (e["now"] in NEED_EXTERNAL and (e.get("external") or e.get("open"))) or (e["now"] == "NOT_RUHAN" and not steps[sid]["ticked"]) or e["now"] == "RESEARCH_NEGATIVE"
        if needs and sid not in covered:
            out.append(f"{sid} ({e['now']}) still needs an outside actor but is in no item of docs/testing/external_testing.json")
    for sid in sorted(covered & set(steps)):
        path = ROOT / "docs" / steps[sid]["file"]
        want = link_block(sid, steps, items)
        if with_block(path.read_text(encoding="utf-8"), want) != path.read_text(encoding="utf-8"):
            out.append(f"{sid}: the step file does not link to its external items; run tools/plans/external_testing.py --link-steps")
    return out


def readiness(item: dict, recon: dict, steps: dict[str, dict]) -> tuple[str, list[str]]:
    """Whether the engineering behind an item is finished, so that the physical or external check can be run now. READY: every step it closes is implementation-complete (ticked). PARTLY READY: some are. NOT READY: none is (the check would be
    testing something that is not built). Steps that are not ours (an outside owner's work with no Ruhan-side engineering) count as complete only when their step file is ticked."""
    done, todo = [], []
    for sid in item["steps"]:
        e = recon["steps"].get(sid, {})
        ok = steps[sid]["ticked"] or e.get("now") == "DONE" or (e.get("now") == "ENG_DONE" and e.get("implementation") == "complete")
        (done if ok else todo).append(sid)
    if not todo:
        return "READY", []
    return ("PARTLY READY" if done else "NOT READY"), todo


def built_lines(i: dict) -> list[str]:
    """What the engineer built and unit-tested for an item, kept apart from the physical test itself (which is NOT RUN until the named person does it)."""
    out: list[str] = []
    if i.get("built_and_unit_tested"):
        out += ["**Built and unit-tested by the engineer** (this is NOT the physical test; the item is NOT RUN until you do it):", ""] + [f"* {x}" for x in i["built_and_unit_tested"]] + [""]
    if i.get("headset_checks"):
        out += ["**Headset checks to run** (what only the device can show; each is NOT RUN):", ""] + [f"* {x}" for x in i["headset_checks"]] + [""]
    return out


def render(data: dict, recon: dict, steps: dict[str, dict]) -> str:
    items = all_items(data)
    status = {i["id"]: result_of(i["id"]) for i in items}
    ready = {i["id"]: readiness(i, recon, steps) for i in items}
    for i in items:                                                   # an item whose engineering is not built cannot be run: BLOCKED, never NOT RUN, until its steps are implemented
        if status[i["id"]][0] == "NOT RUN" and ready[i["id"]][0] == "NOT READY" and i["group"] != "other":
            status[i["id"]] = ("BLOCKED", "")
    count = lambda g: sum(1 for i in items if i["group"] == g)             # noqa: E731
    L = ["# External testing for Sannan and other outside actors (single source of truth)", "",
         f"_Generated by `tools/plans/external_testing.py` from `docs/testing/external_testing.json`, the reconciliation (`docs/plans/reconciliation.json`), the step files and the result files in `docs/testing/results/`; do not edit by hand. Written {data['written']}._", "",
         data["owner"], "",
         f"**{len(items)} items**: {count('device')} headset checks (DC), {count('unity')} Unity, 3D and VR acceptance groups for the P0 plan (UX), {count('other')} items for other people, accounts, permissions and the owner (EX). "
         f"Status: {sum(1 for i in items if status[i['id']][0] == 'PASS')} PASS, {sum(1 for i in items if status[i['id']][0] == 'FAIL')} FAIL, {sum(1 for i in items if status[i['id']][0] == 'NOT RUN')} NOT RUN, {sum(1 for i in items if status[i['id']][0] == 'BLOCKED')} BLOCKED (the engineering it would test is not built yet).",
         f"Readiness of the engineering behind the items: {sum(1 for i in items if ready[i['id']][0] == 'READY')} READY to run, {sum(1 for i in items if ready[i['id']][0] == 'PARTLY READY')} PARTLY READY (run the steps listed as implemented; the others wait for their implementation), {sum(1 for i in items if ready[i['id']][0] == 'NOT READY')} NOT READY.", "",
         "Status words: `NOT RUN` (implemented, waiting for the person), `BLOCKED` (NOT RUN as well: the implementation it would test is not finished, so running it would prove nothing), `PASS`, `FAIL`. A tick on a step file means the engineering is complete and tested; it does NOT mean the item below passed. Only a result file with `Result: PASS` does.", "",
         "## 1. How to use this page", "",
         "1. Find your item in the table in section 2. Each item names the steps it closes, what it needs, the procedure, the pass rule and the evidence to keep.",
         "2. Do the procedure exactly. Do not skip a line because it looks obvious; a skipped line is a missing measurement.",
         "3. Record the outcome in a result file, using this form:", "",
         "   Result file: `" + data["result_form"]["file"] + "` with the fields: " + "; ".join(data["result_form"]["fields"]) + ".", "",
         "   " + data["result_form"]["rule"], "",
         "   Start the file with the line `Result: PASS`, `Result: FAIL` or `Result: NOT RUN`; this page reads that line to show the status below, and CI fails if the page is not regenerated after a result file is added (`uv run --project tools tools/plans/external_testing.py`).", "",
         f"4. **If it fails:** {data['defaults']['failure']}",
         "5. **After it passes:** the engineer named in the item sets the step's status with `tools/plans/tick.py` after reading the result file. Nobody ticks a step because a test was reported verbally.",
         "6. **AI simulation is not human testing.** Synthetic data, AI judges and simulated learners are used for development only; the items below that say people are needed are not satisfied by them.", "",
         "## 2. All items", "", "| ID | What | Who | Closes steps | Features | Readiness | Status |", "|---|---|---|---|---|---|---|"]
    for i in items:
        who = i.get("who", "Sannan")
        st = status[i["id"]]
        L.append(f"| [{i['id']}](#{i['id'].lower()}) | {i['title']} | {who.split('.')[0][:90]} | {', '.join(i['steps'][:6])}{' ...' if len(i['steps']) > 6 else ''} | {', '.join(features_of(i['steps'])) or '-'} | {ready[i['id']][0]} | {st[0]}{(' ([result](' + st[1].replace('docs/testing/', '') + '))') if st[1] else ''} |")
    L += ["", "## 3. Headset checks (Quest, Unity)", "", "Procedures are exact; the pass rule is the only judge. " + data["defaults"]["evidence_device"], ""]
    for i in (x for x in items if x["group"] == "device"):
        L += [f"### {i['id']}", "", f"**{i['title']}**", "", f"* Who: {i.get('who', 'Sannan')}", f"* Why local CI cannot verify it: {WHY['device']}", f"* Needs: {i['needs']}",
              f"* Closes steps: {', '.join(f'[{s}](../{steps[s]["file"].replace(" ", "%20")})' for s in i['steps'])}", f"* Features: {', '.join(features_of(i['steps'])) or '-'} (plans in `docs/plans/features/<ID>.md`)", "* Prepared (already in the repository):"]
        L += [f"  * `{p}`" for p in i["prepared"]]
        L += ["", "Procedure:", ""] + [f"{n}. {t}" for n, t in enumerate(i["procedure"], 1)] + ["", f"**Pass rule:** {i['pass_rule']}", "", f"**Evidence to collect:** {i.get('evidence') or data['defaults']['evidence_device']}",
              f"**Save it in:** `docs/testing/results/{i['id']}.md` and `docs/testing/results/{i['id']}/`.", f"**After it passes:** {i['after']}", f"**Readiness:** {ready[i['id']][0]}" + (f" (not implemented yet: {', '.join(ready[i['id']][1])})" if ready[i['id']][1] else " (every step it closes is implemented and ticked)"), "**Actual result and notes:** none recorded; fill the result file, not this page.", f"**Status:** {status[i['id']][0]}", ""]
        L += built_lines(i)
    L += ["## 4. Unity, 3D and VR acceptance of the P0 plan", "",
          "The engine half of these steps is built and tested by machine (see the reconciliation page); what remains is the Unity scene, prop, screen or headset half. For each step: open the step file, follow its **How to implement**, then do exactly what its **Verification** says and "
          "write one row per step in the group's result file (step id, date, device and build, PASS or FAIL, numbers, evidence). A step passes only when its verification line is true on the device named in the row.", ""]
    for i in (x for x in items if x["group"] == "unity"):
        L += [f"### {i['id']}", "", f"**{i['title']}**", "", f"* Who: {i['who']}", f"* Why local CI cannot verify it: {WHY['unity']}", f"* Needs: {i['needs']}", f"* Features: {', '.join(features_of(i['steps'])) or '-'}",
              f"* Save it in: `docs/testing/results/{i['id']}.md` (one row per step) and `docs/testing/results/{i['id']}/`", f"* Readiness: {ready[i['id']][0]}" + (f" (not implemented yet: {', '.join(ready[i['id']][1])})" if ready[i['id']][1] else " (every step it closes is implemented and ticked)"), "* Actual result and notes: none recorded; fill the result file, not this page.", f"* Status: {status[i['id']][0]}", "", "| Step | Status of the engineering | Acceptance (the step's Verification, verbatim) |", "|---|---|---|"]
        for s in i["steps"]:
            e = recon["steps"].get(s, {})
            L.append(f"| [{s}](../{steps[s]['file'].replace(' ', '%20')}) {steps[s]['title'][:70]} | {e.get('now', '-')}{' (ticked)' if steps[s]['ticked'] else ''} | {steps[s]['verification'][:600].replace('|', '/')} |")
        L.append("")
        L += built_lines(i)
    L += ["## 5. Items for other people, accounts, permissions and the owner", "",
          "Sannan cannot give consent, labelling, clinical or licence authority on anyone's behalf. Each item says who must act. The item stays open until that person's result file exists.", ""]
    for kind, heading in (("people", "5a. People: raters, labellers, listeners, participants"), ("account", "5b. Account holders"), ("permission", "5c. Permissions and licences"), ("owner", "5d. Owner decisions and authoring"), ("device", "5e. Other machines and recordings")):
        group = [x for x in items if x["group"] == "other" and x["kind"] == kind]
        if not group:
            continue
        L += [f"### {heading}", ""]
        for i in group:
            L += [f"#### {i['id']}", "", f"**{i['title']}**", "", f"* Who must act: {i['who']}", f"* Why local CI cannot verify it: {WHY[i['kind']]}", f"* Needs: {i['needs']}",
                  f"* Closes steps: {', '.join(f'[{s}](../{steps[s]["file"].replace(" ", "%20")})' for s in i['steps'])}", f"* Features: {', '.join(features_of(i['steps'])) or '-'}", "* Prepared (already in the repository):"]
            L += [f"  * `{p}`" for p in i["prepared"]]
            L += ["", "Procedure:", ""] + [f"{n}. {t}" for n, t in enumerate(i["procedure"], 1)] + ["", f"**Pass rule:** {i['pass_rule']}", "", "**Evidence to collect:** " + "; ".join(i["evidence"]) + ".",
                  f"**Save it in:** `docs/testing/results/{i['id']}.md`.", f"**After it passes:** {i['after']}", f"**Readiness:** {ready[i['id']][0]}" + (f" (not implemented yet: {', '.join(ready[i['id']][1])})" if ready[i['id']][1] else " (every step it closes is implemented and ticked)"), "**Actual result and notes:** none recorded; fill the result file, not this page.", f"**Status:** {status[i['id']][0]}", ""]
    covered = sorted({s for i in items for s in i["steps"]})
    L += ["## 6. Coverage", "", f"{len(covered)} steps are named by at least one item. The check fails when a step whose reconciliation says an outside actor is still needed is not named here, so this page cannot silently lose a dependency.", "",
          "Not external (so not listed): steps whose reconciliation status is Done or Approved, and steps that only wait for the engineer.", ""]
    return "\n".join(L) + "\n"


def main(argv: list[str]) -> int:
    data, recon, steps = json.loads(DATA.read_text(encoding="utf-8")), json.loads(RECON.read_text(encoding="utf-8")), step_files()
    if "--link-steps" in argv:
        items = all_items(data)
        for sid in sorted({s for i in items for s in i["steps"]} & set(steps)):
            path = ROOT / "docs" / steps[sid]["file"]
            old = path.read_text(encoding="utf-8")
            new = with_block(old, link_block(sid, steps, items))
            if new != old:
                path.write_text(new, encoding="utf-8", newline="\n")
        steps = step_files()
    bad = problems(data, recon, steps)
    if bad:
        print("\n".join("FAIL " + b for b in bad))
        return 1
    text = render(data, recon, steps)
    if "--check" in argv:
        ok = PAGE.exists() and PAGE.read_text(encoding="utf-8") == text
        print("external testing page " + ("current" if ok else "OUT OF DATE: run tools/plans/external_testing.py"))
        return 0 if ok else 1
    PAGE.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", PAGE.relative_to(ROOT).as_posix(), f"({len(all_items(data))} items)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
