"""The Ruhan and Moiz inventory (129 steps on 18 October 2026, 126 since the three retired classifier steps were removed on 27 October 2026, ADR-0029) against the latest repository: `uv run --project tools tools/plans/ruhan_moiz_inventory.py [--check]` writes docs/plans/ruhan-moiz-inventory.md.

The steps counted are those whose reconciliation owner names Ruhan or Moiz, except the voice client (p1-voice-input-s02), which was Sannan's and was built by Ruhan on 25 Oct 2026 (UTC) under the owner's one-time authorisation; it is listed
beside them. Each step falls in exactly one class, from its status in docs/plans/reconciliation.json:

  completed            DONE, or a Moiz step the owner approved (ticked)
  engineering_done     ENG_DONE: built and tested; what remains is acceptance only a person or a device can give
  gated_off            DONE_GATE_OFF: built and tested, the feature switch stays OFF until human evidence exists
  conditional          RESEARCH_NEGATIVE: analysed, the trigger has not occurred, nothing is built
  external             BLOCKED or PARTLY: the missing piece is a source, a person or a device
  unfinished           anything else: implementation that is not done

The count of `unfinished` is the number the owner asked to be zero. Register rows that are not steps (docs/deferred-tasks.md) are counted in docs/plans/register-triage.md.
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "docs" / "plans" / "reconciliation.json"
OUT = ROOT / "docs" / "plans" / "ruhan-moiz-inventory.md"
BUILT_FOR_SANNAN = {"p1-voice-input-s02"}
CLASSES = [("completed", "Completed engineering (done, or a Moiz step approved by the owner)"), ("engineering_done", "Engineering done; only outside acceptance remains"),
           ("gated_off", "Built and tested; the feature switch is OFF until human evidence exists"), ("conditional", "Research trigger not met (nothing to build unless it occurs)"), ("assigned", "Assigned in the front-end split of 29 Oct 2026; not started yet (listed, not counted as unfinished)"), ("external", "Waiting on a source, a person or a device"), ("unfinished", "Unfinished implementation")]


def klass(e: dict) -> str:
    now = e["now"]
    if now == "DONE" or (now == "NOT_RUHAN" and "Moiz" in e["owner"]):
        return "completed"
    if now == "ENG_DONE":
        return "engineering_done"
    if now == "DONE_GATE_OFF":
        return "gated_off"
    if now == "RESEARCH_NEGATIVE":
        return "conditional"
    if now in ("BLOCKED", "PARTLY"):
        return "external"
    if now == "ASSIGNED":          # a front-end step handed to Ruhan or Moiz in the confirmed split (docs/plans/frontend/front_end_load_distribution.md), not started yet
        return "assigned"
    return "unfinished"


def build() -> tuple[str, dict]:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    steps = data.get("steps") or data
    mine = {k: v for k, v in steps.items() if ("Ruhan" in v["owner"] or "Moiz" in v["owner"]) and k not in BUILT_FOR_SANNAN}
    by = {c: sorted(k for k, v in mine.items() if klass(v) == c) for c, _ in CLASSES}
    counts = {c: len(by[c]) for c, _ in CLASSES}
    L = [f"# Ruhan and Moiz inventory (the {len(mine)} steps)", "", "_Generated by `tools/plans/ruhan_moiz_inventory.py` from `docs/plans/reconciliation.json`; do not edit by hand._", "",
         f"Total: **{len(mine)}** steps. Unfinished implementation: **{counts['unfinished']}**. The voice client `p1-voice-input-s02` (Sannan's, built by Ruhan on 25 Oct 2026 UTC under the owner's authorisation) is counted separately and is engineering done (its Quest checks are DC-08 and DC-11).", "",
         "| Class | Steps |", "|---|---|"] + [f"| {t} | {counts[c]} |" for c, t in CLASSES] + ["", f"Historical statement of 18 October 2026: DONE 70, ENG_DONE 41, DONE_GATE_OFF 4, open 4, research trigger not met 2, reassigned 8 = 129. On 27 October 2026 the three retired classifier steps (p1-ai-language-s06, p1-ai-language-s07, p2-ai-extensions-s03) were removed under ADR-0029, which leaves {len(mine)}. "
         "Since then three steps moved from DONE_GATE_OFF or open to ENG_DONE or retired by evidence (listed below).", ""]
    for c, t in CLASSES:
        L += [f"## {t} ({counts[c]})", ""]
        for k in by[c]:
            v = mine[k]
            extra = v.get("external") or v.get("open") or ""
            L.append(f"- `{k}` ({v['owner']})" + (f": {extra[:240]}" if extra and c != "completed" else ""))
        L.append("")
    return "\n".join(L) + "\n", counts


if __name__ == "__main__":
    text, counts = build()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("Ruhan and Moiz inventory " + ("current" if ok else "OUT OF DATE: run tools/plans/ruhan_moiz_inventory.py"))
        sys.exit(0 if ok and counts["unfinished"] == 0 else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(counts, sum(counts.values()))
