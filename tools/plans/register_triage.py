"""Triage of the open rows of docs/deferred-tasks.md: `uv run --project tools tools/plans/register_triage.py [--check]` writes docs/plans/register-triage.md.

Each open row (status Pending, Blocked or In progress) is put in one class by the text of its own "needs" column, so the class is as honest as that column; a row whose column names no outside party is listed as
"engineering to verify" and is the list that is worked through by hand. Completed rows are only counted.
"""
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "docs" / "deferred-tasks.md"
OUT = ROOT / "docs" / "plans" / "register-triage.md"
CLASSES = [
    ("people", "Waiting on people: a clinician, raters, labellers, listeners, participants or a qualified reviewer", r"clinician|rater|labeller|reviewer|participants|listens|a person who|a person reads|qualified|terminologist|transcrib|surgeon|speakers|human|two people|teacher|recruit"),
    ("headset", "Waiting on the headset or Sannan's Unity work", r"sannan|quest|headset|unity|dc-\d\d|scenes and assets"),
    ("owner", "Waiting on an owner decision, account or approval", r"owner|decide|decision|approval|github pro|public repo|licen[cs]e|supabase|render|domain|paying|customer|paid plan|first push|moiz|dependabot|invitation"),
    ("later", "Later by design: a trigger that has not occurred (customer, scale, release, merge, laptop)", r"when a customer|before real customers|before a release|more than a handful|if supervisors|laptop|when the backend branches|first generated|ongoing duty|next clone|fastapi or starlette"),
]


def rows():
    out = []
    for line in SRC.read_text(encoding="utf-8").splitlines():
        if not re.match(r"\|\s*DT-\d+\s*\|", line):
            continue
        cells = [c.strip() for c in re.split(r"(?<!\\)\|", line.strip().strip("|"))]
        if len(cells) < 5:
            continue
        out.append({"id": cells[0], "status": re.sub(r"[*]", "", cells[2]).split(" ")[0] if "In progress" not in cells[2] else "In progress", "what": cells[1], "needs": cells[4], "notes": cells[5] if len(cells) > 5 else ""})
    return out


def classify(r):
    text = (r["needs"] + " " + r["what"][:200]).lower()
    for key, _, pat in CLASSES:
        if re.search(pat, (r["needs"] + " " + r["notes"][:240]).lower()):
            return key
    return "engineering"


def render():
    rs = [r for r in rows() if r["status"] != "Completed"]
    done = sum(1 for r in rows() if r["status"] == "Completed")
    by = defaultdict(list)
    for r in rs:
        by[classify(r)].append(r)
    L = ["# Register triage", "", "_Generated by `tools/plans/register_triage.py` from `docs/deferred-tasks.md`; do not edit by hand._", "",
         f"The register has {len(rs) + done} rows: {done} completed and {len(rs)} open. Each open row is placed in one class by the text of its own needs column (the first class whose pattern matches, in the order below); rows whose column names no outside party are \"engineering to verify\" and are worked through by hand. "
         "The class says what the row waits for, not that the work is useless: a row waiting on a person can still have its engineering half done.", ""]
    L += ["| Class | Rows |", "|---|---|"] + [f"| {t} | {len(by[k])} |" for k, t, _ in CLASSES] + [f"| Engineering to verify (no outside party named) | {len(by['engineering'])} |", ""]
    for k, t, _ in CLASSES + [("engineering", "Engineering to verify", "")]:
        L += [f"## {t}", "", "| Row | Status | What | Waiting for |", "|---|---|---|---|"]
        for r in by[k]:
            L.append(f"| {r['id']} | {r['status']} | {r['what'][:150].replace('|', '/')} | {r['needs'][:150].replace('|', '/')} |")
        L.append("")
    return "\n".join(L) + "\n", {k: len(v) for k, v in by.items()}


if __name__ == "__main__":
    text, counts = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("register triage " + ("current" if ok else "OUT OF DATE: run tools/plans/register_triage.py"))
        sys.exit(0 if ok else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(counts)
