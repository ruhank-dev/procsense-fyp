def coverage_audit(doc, nodes) -> str:
    cov = coverage(doc)
    pct = lambda n: f"{100 * n / cov['total']:.0f}%" if cov["total"] else "0%"
    gaps = [r for r in cov["rows"] if not r["complete"] or not r["mapped"] or not r["acceptance"]]
    out = ["# Feature coverage audit", "", HEAD, "",
           "Computed from the pipeline JSON by the same function the validator uses (`coverage()` in `tools/plans/validate_pipeline.py`). A plan counts as complete only if every plan field, all seven AI questions, "
           "integration, staged versions, and every capability's schemas, flow, validation, five failure cases, tests, metrics, baseline, acceptance, both-GPU hardware notes and tasks are present, and AI features have a "
           "separate AI capability. A feature counts as mapped only if every task has a step file and sits in a roadmap phase.", "", "## Totals", ""]
    out += table(["Measure", "Count", "Share"], [["Features", cov["total"], "100%"], ["Complete implementation plans", cov["complete"], pct(cov["complete"])],
                                                  ["Mapped to concrete, phased tasks", cov["mapped"], pct(cov["mapped"])], ["Acceptance criteria on every capability", cov["acceptance"], pct(cov["acceptance"])],
                                                  ["Capability plans", cov["capabilities"], "—"], ["of which AI capabilities", cov["ai_capabilities"], "—"]])
    out += ["## Gaps", ""] + (["None: every feature has a complete plan, phased tasks and acceptance criteria."] if not gaps else [f"- {r['id']}: {'; '.join(r['problems']) or 'unmapped task'}" for r in gaps]) + ["", "## Coverage matrix", ""]
