def dataset_matrix(doc, nodes) -> str:
    feats = {n["id"]: n for n in nodes.values() if n["type"] == "feature"}
    out = ["# Dataset and data-to-feature matrix", "", HEAD, "",
           "What each dataset and content table is, what is known about its normal and abnormal patterns, what analysis is still needed, and which pipeline nodes and features use it. "
           "Licences and conditions: `docs/research/licence_provenance_register.md`.", "", "## Datasets", ""]
    out += table(["ID", "Dataset", "Licence", "Status", "Modality", "Used for", "Derived files", "Feeds nodes", "Features"],
                 [[d["id"], f"{d['name']} {d['version']}", d["licence"], d["status"], d["modality"], d["use"], d["derived"], d["feeds"], d["features"]] for d in doc["datasets"]])
    out += ["## Normal and abnormal patterns (known) and analysis still needed", ""]
    out += table(["ID", "What is known", "Analysis planned", "Restrictions"], [[d["id"], d["normal_abnormal"], d["planned_analysis"], d["restrictions"]] for d in doc["datasets"]])
    out += ["## Content stores", ""]
    users = defaultdict(set)
    for f in feats.values():
        for d in f["dataset_refs"]:
            users[d].add(f["id"])
    stores = [n for n in nodes.values() if n["type"] == "store"]
    flows = defaultdict(set)
    for e in doc["edges"]:
        if e["source"].startswith("ST-") and e["type"] == "uses_data":
            flows[e["source"]].add(e["target"])
    out += table(["ID", "Store", "Status", "Location", "Read by nodes", "Features"],
                 [[s["id"], s["label"], s["status"], s["location"], sorted(flows[s["id"]]), sorted(users[s["id"]], key=fid_key)] for s in stores])
    out += ["## Feature by data (generation method per data type)", ""]
    rows = [[f["id"], f["label"], f["dataset_refs"], f["model_refs"], f["method"]] for f in sorted(feats.values(), key=lambda f: fid_key(f["id"])) if f["dataset_refs"]]
    out += table(["Feature", "Name", "Data", "Models", "Method"], rows)
    return "\n".join(out)


