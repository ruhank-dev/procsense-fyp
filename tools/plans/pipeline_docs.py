def mermaid(doc, nodes) -> str:
    keep = {"entry", "exit", "fallback", "stage", "offline_step"}
    groups = {g["id"]: g for g in doc["groups"]}
    lines = ["%% Generated by tools/plans/pipeline_docs.py from procsense_full_pipeline.json — do not edit by hand.", "flowchart TD"]
    by_group = defaultdict(list)
    for n in nodes.values():
        if n["type"] in keep:
            by_group[n["group"]].append(n)
    for gid, ns in by_group.items():
        lines.append(f'  subgraph {gid}["{groups[gid]["label"]}"]')
        for n in sorted(ns, key=lambda n: n["id"]):
            lab = f"{n['id']} {n['label']}".replace('"', "'")
            lines.append(f'    {n["id"].replace("-", "_")}["{lab}<br/><i>{n["status"]}</i>"]')
        lines.append("  end")
    arrows = {"data_flow": "-->", "control": "-.->", "repair": "-.->", "fallback": "-.->", "feedback": "-.->", "produces": "-->"}
    for e in doc["edges"]:
        if e["type"] in arrows and nodes[e["source"]]["type"] in keep and nodes[e["target"]]["type"] in keep:
            lab = (e["label"] or e["type"]).replace('"', "'")
            lines.append(f'  {e["source"].replace("-", "_")} {arrows[e["type"]]}|"{lab}"| {e["target"].replace("-", "_")}')
    return "\n".join(lines) + "\n"


def cytoscape(doc, nodes) -> str:
    els = [{"group": "nodes", "data": {"id": g["id"], "label": g["label"], "kind": "group", **({"parent": g["parent"]} if g.get("parent") else {})}} for g in doc["groups"]]
    for n in doc["nodes"]:
        data = {"id": n["id"], "label": f"{n['id']} {n['label']}", "type": n["type"], "status": n.get("status", ""), "parent": n["group"]}
        els.append({"group": "nodes", "data": data, "classes": n["type"]})
    for e in doc["edges"]:
        els.append({"group": "edges", "data": {"id": e["id"], "source": e["source"], "target": e["target"], "type": e["type"], "label": e["label"], "cycle": "cycle" in e},
                    "classes": e["type"] + (" cycle" if "cycle" in e else "")})
    return json.dumps({"format_version": "1.0", "generated_from": "procsense_full_pipeline.json", "elements": els}, indent=1, ensure_ascii=False) + "\n"


def plans_pointer(doc, nodes):
    feats = [n for n in doc["nodes"] if n["type"] == "feature"]
    return "\n".join(["# Feature plans: where they are", "",
        "The complete implementation plans of all %d features are **not stored here**. The one canonical copy of each is `docs/plans/features/<ID>.md`, generated by `tools/plans/pipeline_docs.py` from [../procsense_full_pipeline.json](../procsense_full_pipeline.json). This folder is only an entry point so the plans are found from the architecture set; do not add plan files here." % len(feats), "",
        "Start from the [feature registry](../feature_registry.md), or open one plan:", "",
        "| ID | Feature | Plan |", "|---|---|---|"] + [f"| {f['id']} | {f['label']} | [{f['id']}.md](../../plans/features/{f['id']}.md) |" for f in feats] + [""])


def main() -> int:
    doc = json.loads(SRC.read_text(encoding="utf-8"))
    nodes = {n["id"]: n for n in doc["nodes"]}
    outputs = {"feature_registry.md": feature_registry, "live_generation_spec.md": live_spec, "dataset_feature_matrix.md": dataset_matrix,
               "model_technology_register.md": model_register, "master_roadmap.md": roadmap, "pipeline_overview.mmd": mermaid,
               "procsense_pipeline.cytoscape.json": cytoscape}
    outputs["feature_coverage_audit.md"] = coverage_audit
    outputs["feature_plans/README.md"] = plans_pointer
    for f in (n for n in doc["nodes"] if n["type"] == "feature"):
        outputs[f"{PLANS}/{f['id']}.md"] = (lambda fe: (lambda d, n: feature_plan(d, n, fe)))(f)
    import pipeline_flows
    for fname, flow in pipeline_flows.build(doc).items():
        outputs[f"flows/{fname}"] = (lambda fl: (lambda d, n: pipeline_flows.render(fl)))(flow)
    (ARCH / "feature_plans").mkdir(exist_ok=True)
    (ARCH / "flows").mkdir(exist_ok=True)
    stale = []
    for name, fn in outputs.items():
        text = fn(doc, nodes)
        text = text if text.endswith("\n") else text + "\n"
        path = ARCH / name
        if "--check" in sys.argv:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        print("out of date (run tools/plans/pipeline_docs.py): " + ", ".join(stale))
        return 1
    print(f"{len(outputs)} planning files {'up to date' if '--check' in sys.argv else 'written'} in docs/architecture")
    return 0


if __name__ == "__main__":
    sys.exit(main())
