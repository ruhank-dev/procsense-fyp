"""The persistent execution queue of the engineering work that is still open (owner instruction, 25 October 2026): `docs/plans/execution-queue.md`.

    uv run --project tools tools/plans/execution_queue.py            # write
    uv run --project tools tools/plans/execution_queue.py --check    # fail if the page is out of date

It is generated from `docs/plans/reconciliation.json` (every step and its status) and `docs/deferred-tasks.md` (every DT item), so it can never disagree with them. For each open item it gives the id,
the owner, the status, what remains, what it depends on, the next implementation action, the tests it needs and the evidence once done. An item is `engineering` when code, content or tests can finish it
without a person or a device, `external` when it needs people, an account, a licence or the headset (Sannan), and `others` when the step belongs to another owner and is not a dependency of Ruhan's or
Moiz's work. Steps already finished are not listed (their evidence is in task-reconciliation.md).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RECON = ROOT / "docs" / "plans" / "reconciliation.json"
DEFERRED = ROOT / "docs" / "deferred-tasks.md"
OUT = ROOT / "docs" / "plans" / "execution-queue.md"
EXTERNAL = re.compile(r"(?i)\b(sannan|headset|quest|clinician|owner|labeller|raters?|account holder|pharmacist|people|participants?|licen[cs]e|laptop|consent|customer|decision)\b")
DONE = {"DONE", "ENG_DONE"}


def step_rows() -> list[dict]:
    data = json.loads(RECON.read_text(encoding="utf-8"))["steps"]
    rows = []
    for sid, s in sorted(data.items()):
        if s["now"] in DONE:
            continue
        ext = s.get("external", "") or ""
        if s["now"] == "NOT_RUHAN":
            kind = "others"
        elif s["now"] in ("RESEARCH_NEGATIVE",):
            kind = "research (trigger not met)"
        elif s["now"] == "BLOCKED" or (EXTERNAL.search(ext) and "engineering" not in s.get("open", "").lower() and s["now"] != "PARTLY"):
            kind = "external"
        else:
            kind = "engineering" if s["now"] == "PARTLY" else "external"
        rows.append({"id": sid, "owner": s["owner"], "status": s["now"], "kind": kind, "open": (s.get("open") or "")[:260], "external": ext[:200],
                     "evidence": ", ".join(s.get("evidence", [])[:3])})
    return rows


def dt_rows() -> list[dict]:
    rows = []
    for line in DEFERRED.read_text(encoding="utf-8").splitlines():
        m = re.match(r"\| (DT-\d+) \| (.*?) \| (Pending|In progress|Blocked) \| (.*?) \| (.*?) \| ?(.*?) \|?$", line)
        if not m:
            continue
        dt, what, status, plan, dep, note = m.groups()
        text = dep + " " + what
        if re.search(r"(?i)\b(sannan|unity|headset|quest)\b", text):
            owner = "Sannan (Unity/headset)"
        elif re.search(r"(?i)\bmoiz\b|backend|supabase|render|deploy", text):
            owner = "Moiz (backend)"
        else:
            owner = "Ruhan"
        kind = "external" if EXTERNAL.search(dep) and status == "Blocked" else ("external" if re.search(r"(?i)\b(owner|clinician|labeller|people|account|customer|licen[cs]e|laptop|participants)\b", dep) else "engineering")
        rows.append({"id": dt, "owner": owner, "status": status, "kind": kind, "open": what[:200], "external": dep[:160], "evidence": note[:100]})
    return rows


def render() -> str:
    steps, dts = step_rows(), dt_rows()
    eng_steps = [r for r in steps if r["kind"] == "engineering"]
    lines = ["# Execution queue: the engineering work still open", "",
             "_Generated by `tools/plans/execution_queue.py` from `reconciliation.json` and `deferred-tasks.md`; do not edit by hand. It lists only unfinished items. For each: the owner, the status, what remains, its dependency, the next action, the test it needs and the evidence that closes it._", "",
             f"**{len(eng_steps)} steps** have engineering still open, **{sum(1 for r in steps if r['kind'] == 'external')}** wait for people, an account, a licence or the headset, "
             f"**{sum(1 for r in steps if r['kind'] == 'others')}** belong to other owners (mostly Sannan's Unity and Blender work), and **{sum(1 for r in steps if r['kind'].startswith('research'))}** are research items whose trigger is not met. "
             f"Of {len(dts)} open register items, **{sum(1 for r in dts if r['kind'] == 'engineering')}** can be finished by engineering alone.", "",
             "Next action rule: take the first `engineering` row whose dependency is satisfied, implement it, add or update its test, run the suites (`task ci`, and Unity EditMode and PlayMode for Unity work), update the register and reconciliation, commit, push, then take the next row.", "",
             "## Steps (reconciliation)", "", "| Step | Owner | Status | Kind | What remains | Waits for | Test it needs | Evidence so far |", "|---|---|---|---|---|---|---|---|"]
    for r in steps:
        test = "Unity EditMode and PlayMode" if "Unity" in r["owner"] or "Sannan" in r["external"] else "unit and integration test named in the step file; `task ci`"
        lines.append(f"| {r['id']} | {r['owner']} | {r['status']} | {r['kind']} | {r['open'] or '-'} | {r['external'] or '-'} | {test} | {r['evidence'] or '-'} |")
    lines += ["", "## Register items (deferred-tasks.md)", "", "| Item | Owner (by wording) | Status | Kind | What remains | Depends on | Completion evidence |", "|---|---|---|---|---|---|---|"]
    for r in dts:
        lines.append(f"| {r['id']} | {r['owner']} | {r['status']} | {r['kind']} | {r['open']} | {r['external'] or '-'} | on completion: the test or file that proves it, recorded in the register row |")
    return "\n".join(lines).replace("|", "|") + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            print("FAIL  docs/plans/execution-queue.md is out of date: run `uv run --project tools tools/plans/execution_queue.py`")
            return 1
        print("docs/plans/execution-queue.md is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
