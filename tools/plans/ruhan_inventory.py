def grep(pattern: str, paths: list[str]) -> bool:
    out = subprocess.run(["git", "grep", "--untracked", "-l", "-i", "-E", pattern, "--", *paths], cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace")
    return bool(out.stdout.strip())


def main() -> int:
    rows = []
    for line in INDEX.read_text(encoding="utf-8").splitlines():
        m = re.match(r"\| (P3-[A-Z]+-\d+) (.*?) \| \[[^\]]+\]\([^)]+\) \| Ruhan \| ([^|]*) \| ([^|]*) \|\s*$", line)
        if m:
            rows.append((m.group(1), re.sub(r"\s+", " ", m.group(2))[:110], m.group(4).strip()))
    lines = ["# Ruhan-owned P3 tasks: claimed status against the code (generated)", "",
             "_Generated by `tools/plans/ruhan_inventory.py` from `docs/plans/p3/p3-task-index.md`. Evidence = a name search for the identifiers the task names; it shows a thing exists, not that it is correct or reviewed. Items marked label only were not checked in code._", "",
             "| Task | What | Claimed | Evidence in code | Found / searched |", "|---|---|---|---|---|"]
    counts = {"evidence found": 0, "partial": 0, "not found in code": 0, "label only": 0}
    for tid, what, claimed in rows:
        pats, paths = EVIDENCE.get(tid, ([], []))
        if not pats:
            verdict, detail = "label only", ""
        else:
            hits = [grep(p, paths) for p in pats]
            verdict = "evidence found" if all(hits) else "partial" if any(hits) else "not found in code"
            detail = ", ".join(f"`{p}` {'yes' if h else 'no'}" for p, h in zip(pats, hits))
        counts[verdict] += 1
        lines.append(f"| {tid} | {what} | {claimed} | {verdict} | {detail} |")
    lines += ["", f"Totals ({len(rows)} Ruhan-owned P3 tasks): " + ", ".join(f"{k} {v}" for k, v in counts.items()) + ".", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(OUT.relative_to(ROOT), counts)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
