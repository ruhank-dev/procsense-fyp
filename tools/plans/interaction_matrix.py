"""Generates docs/plans/p3/interaction-matrix.md, the interaction coverage matrix (P3-INT-01).

    uv run --project tools tools/plans/interaction_matrix.py            # write
    uv run --project tools tools/plans/interaction_matrix.py --check    # exit 1 when the page is not what the sources give

One row per verb. Sources: the engine source (a verb counts as known when its name appears as a string literal in src/ProcSense.Core; the engine registers verbs through constants and loops, so its list cannot be read exactly and engine-only verbs are not enumerated), the interaction catalogue (content/ui/interactions.json,
P3-CTX-01: entities, wrist menu, spoken flag) and the physical emitters serialised in scenes and prefabs (`verb:` lines under unity/Assets). Nothing is
guessed: a column is "yes" only when a source shows it. Catalogue or scene verbs the engine source never names are reported as gaps. The goal-by-goal check (menu only, voice only) is P3-INT-10 and is not done here.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "plans" / "p3" / "interaction-matrix.md"
CORE = ROOT / "src" / "ProcSense.Core"
UNITY = ROOT / "unity" / "Assets"
CATALOGUE = ROOT / "content" / "ui" / "interactions.json"
LITERAL = re.compile(r'"([a-z][a-z_0-9]*)"')
EMITTER = re.compile(r"^\s+verb: ([a-z_0-9]+)\s*$", re.M)


def engine_verbs() -> set[str]:
    out: set[str] = set()
    for p in sorted(CORE.rglob("*.cs")):
        out |= set(LITERAL.findall(p.read_text(encoding="utf-8", errors="replace")))
    return out


def emitter_verbs() -> dict[str, int]:
    counts: dict[str, int] = {}
    for pat in ("*.unity", "*.prefab"):
        for p in sorted(UNITY.rglob(pat)):
            if "Samples" in p.parts or "Packages" in p.parts:
                continue
            for v in EMITTER.findall(p.read_text(encoding="utf-8", errors="replace")):
                counts[v] = counts.get(v, 0) + 1
    return counts


def build() -> str:
    cat = json.loads(CATALOGUE.read_text(encoding="utf-8"))
    engine, emitters = engine_verbs(), emitter_verbs()
    by_id = {e["id"]: e for e in cat["entries"]}
    ents: dict[str, set[str]] = {}
    for ent in cat["entities"]:
        for g in ent["groups"]:
            for i in g["entries"]:
                ents.setdefault(by_id[i]["verb"], set()).add(ent["id"])
    wrist = {by_id[i]["verb"] for i in cat["global"]["entries"]}
    n_entries: dict[str, int] = {}
    spoken: set[str] = set()
    for e in cat["entries"]:
        n_entries[e["verb"]] = n_entries.get(e["verb"], 0) + 1
        if e["voice"]["spoken"]:
            spoken.add(e["verb"])
    verbs = sorted(set(n_entries) | set(emitters))
    yn = lambda b: "yes" if b else "-"  # noqa: E731
    lines = ["# Interaction coverage matrix (P3-INT-01)", "",
             "Generated by `tools/plans/interaction_matrix.py` from the engine source, `content/ui/interactions.json` and the emitters serialised in scenes and prefabs. "
             "Do not edit by hand; `--check` runs in CI. A column says \"yes\" only when a source shows it. The goal-by-goal check (menu only, voice only) is P3-INT-10.", "",
             f"Verbs: {len(verbs)}; named in the engine source: {len(set(verbs) & engine)}; with a catalogue entry: {len(n_entries)}; with a physical emitter in a scene or prefab: {len(emitters)}; "
             f"spoken by the catalogue: {len(spoken)}.", "",
             "| Verb | In engine source | Catalogue entries | Contextual entities | Wrist menu | Voice (catalogue) | Physical emitters (scenes, prefabs) |", "|---|---|---|---|---|---|---|"]
    for v in verbs:
        lines.append(f"| {v} | {yn(v in engine)} | {n_entries.get(v, 0) or '-'} | {', '.join(sorted(ents.get(v, []))) or '-'} | {yn(v in wrist)} | {yn(v in spoken)} | {emitters.get(v, '-')} |")
    gaps = [("Catalogue verbs the engine source never names", sorted(set(n_entries) - engine)),
            ("Scene or prefab emitter verbs the engine source never names", sorted(set(emitters) - engine)),
            ("Catalogue verbs reachable by no entity and not by the wrist menu", sorted(v for v in n_entries if v not in ents and v not in wrist)),
            ("Catalogue verbs with no physical emitter (menu or voice only today)", sorted(set(n_entries) - set(emitters)))]
    for title, items in gaps:
        lines += ["", f"## {title}", "", (", ".join(items) if items else "none")]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        have = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if have != text:
            print("FAIL  docs/plans/p3/interaction-matrix.md is out of date; run tools/plans/interaction_matrix.py")
            return 1
        print("ok    interaction matrix up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
