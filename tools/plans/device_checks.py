"""The headset test register for Sannan (`docs/plans/device_checks.json` -> `docs/plans/sannan-device-checks.md`): `uv run --project tools tools/plans/device_checks.py [--check]`.

Every step whose reconciliation entry needs a headset or a Unity build (the reconciliation names Sannan or the Quest) must appear in at least one check with a procedure and a pass rule, every file a check
prepares must exist, and the generated page must match. Nothing in the register is a result: the result form (`docs/plans/device-results/`) is empty until a person records one.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "docs" / "plans" / "device_checks.json"
RECON = ROOT / "docs" / "plans" / "reconciliation.json"
PAGE = ROOT / "docs" / "plans" / "sannan-device-checks.md"
NEEDS = re.compile(r"Sannan|Quest|headset", re.I)


def needing_a_device(recon: dict) -> set[str]:
    out = set()
    for sid, e in recon["steps"].items():
        if e["now"] == "NOT_RUHAN":
            continue
        if NEEDS.search(e.get("open", "")) or NEEDS.search(e.get("external", "")):
            out.add(sid)
    return out


def problems(data: dict, recon: dict) -> list[str]:
    out = []
    ids = [c["id"] for c in data["checks"]]
    if len(ids) != len(set(ids)):
        out.append("duplicate check ids")
    covered = {s for c in data["checks"] for s in c["steps"]}
    for sid in sorted(needing_a_device(recon) - covered):
        out.append(f"{sid} needs a device (its reconciliation entry names Sannan or the Quest) but no check covers it")
    for sid in sorted(covered - set(recon["steps"])):
        out.append(f"a check names {sid}, which is not a step")
    for c in data["checks"]:
        for key in ("title", "needs", "procedure", "pass_rule"):
            if not c.get(key):
                out.append(f"{c['id']}: no {key}")
        for p in c.get("prepared", []):
            if not (ROOT / p).exists():
                out.append(f"{c['id']}: prepared file {p} does not exist")
    return out


def render(data: dict) -> str:
    L = ["# Headset and Unity checks for Sannan (generated)", "",
         f"_Generated by `tools/plans/device_checks.py` from `docs/plans/device_checks.json`; do not edit by hand. Written {data['written']}._", "",
         data["owner"], "",
         "Each check names the steps it closes, what it needs, the files and commands already prepared, a procedure and a pass rule. Record every result in a file, using this form:", "",
         "Result file: `" + data["result_form"]["file"] + "` with the fields: " + "; ".join(data["result_form"]["fields"]) + ".", "", data["result_form"]["rule"], "",
         "| Check | Closes steps | Needs |", "|---|---|---|"]
    L += [f"| [{c['id']}](#{c['id'].lower()}) {c['title']} | {', '.join(c['steps'])} | {c['needs']} |" for c in data["checks"]]
    for c in data["checks"]:
        L += ["", f"## {c['id']}", "", f"**{c['title']}**", "", f"Needs: {c['needs']}", "", "Prepared (already in the repository):", ""]
        L += [f"* `{p}`" for p in c["prepared"]]
        L += ["", "Procedure:", ""] + [f"{i}. {t}" for i, t in enumerate(c["procedure"], 1)] + ["", f"**Pass rule:** {c['pass_rule']}"]
    return "\n".join(L) + "\n"


def main(argv: list[str]) -> int:
    data, recon = json.loads(DATA.read_text(encoding="utf-8")), json.loads(RECON.read_text(encoding="utf-8"))
    bad = problems(data, recon)
    if bad:
        print("\n".join("FAIL " + b for b in bad))
        return 1
    text = render(data)
    if "--check" in argv:
        ok = PAGE.exists() and PAGE.read_text(encoding="utf-8") == text
        print("device checks " + ("current" if ok else "OUT OF DATE: run tools/plans/device_checks.py"))
        return 0 if ok else 1
    PAGE.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", PAGE.relative_to(ROOT).as_posix(), f"({len(data['checks'])} checks)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
