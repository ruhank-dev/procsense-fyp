"""The final engineering audit: `uv run --project tools tools/plans/engineering_audit.py [--check]` writes docs/plans/engineering-audit.md.

One page that answers "is any actionable engineering left?" from the sources of truth, not from memory: the feature matrix (every plan and what it is), the 129-step inventory, and the open rows of the register by what each waits for.
It FAILS (exit 1 with --check) when the inventory has an unfinished step, when a feature is "Partly built" without a recorded measured shortfall, or when an open register row is classed as engineering without a named reason. The page lists, in words, every
feature that is not engineering complete and every open register row, so nothing is hidden in a count.
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import feature_matrix as FM  # noqa: E402
import register_triage as RT  # noqa: E402
import ruhan_moiz_inventory as INV  # noqa: E402

OUT = ROOT / "docs" / "plans" / "engineering-audit.md"
DONE_RESULTS = ("Complete", "Engineering complete", "Engineering complete, gated off")
# engineering rows that wait on no outside party but are deliberately not built, each with the reason (a register row of this list is not "unfinished": it is decided)
DECIDED = {"DT-048": "each teammate runs `task setup` once; it is an action by people", "DT-128": "deferred until supervisors say the static pages are not enough (a trigger, not a task)",
           "DT-155": "needs the hosting provider's published retention; outside the service's control", "DT-222": "needs the account holder to accept the MedGemma terms and 50 human ratings"}


def build() -> tuple[str, list[str]]:
    ctx = FM.load()
    rows = [FM.derive(n, ctx) for n in ctx["doc"]["nodes"] if n["type"] == "feature"]
    labels = {n["id"]: n["label"] for n in ctx["doc"]["nodes"] if n["type"] == "feature"}
    by = Counter(r["result"] for r in rows)
    text, counts = INV.build()
    problems = []
    if counts["unfinished"]:
        problems.append(f"the inventory has {counts['unfinished']} unfinished step(s)")
    L = ["# Engineering audit", "", "_Generated by `tools/plans/engineering_audit.py`; do not edit by hand._", "",
         f"**Features:** {len(rows)} plans. " + ", ".join(f"{v} {k}" for k, v in sorted(by.items(), key=lambda x: -x[1])) + ". A plan file carries the `[x] ` prefix when its feature is Complete, Engineering complete or Engineering complete with its switch off.", "",
         f"**The 129 Ruhan and Moiz steps:** " + ", ".join(f"{counts[c]} {t.split(' (')[0].lower()}" for c, t in INV.CLASSES) + ".", "", "## Features that are not engineering complete", ""]
    for r in rows:
        if r["result"] in DONE_RESULTS:
            continue
        why = "; ".join([*(f"{k}: {v[:260]}" for k, v in r["unbuilt"].items()), *(r["overlay"].get("retired", "") and [r["overlay"]["retired"][:260]] or [])]) or "an analysed research item whose trigger has not occurred" if r["result"] == "Research: trigger not met" else \
            "; ".join([*(f"{k}: {v[:260]}" for k, v in r["unbuilt"].items()), *(([r["overlay"]["retired"][:260]]) if r["overlay"].get("retired") else [])])
        if r["result"] == "Partly built" and not r["unbuilt"]:
            problems.append(f"{r['id']} is partly built with no recorded shortfall")
        L.append(f"- **{r['id']} {labels[r['id']][:60]}**: {r['result']}. {why}")
    L += ["", "## Features that are engineering complete with their switch off, and why", ""]
    for r in rows:
        if r["result"] == "Engineering complete, gated off":
            L.append(f"- **{r['id']} {labels[r['id']][:60]}**: {r['overlay'].get('engineering_complete', '')[:300]}")
    L += ["", "## Open register rows", "", "Every open row of `docs/deferred-tasks.md` by what it waits for (the full list is `docs/plans/register-triage.md`). The rows below are the ones that name no outside party:", ""]
    rs = [r for r in RT.rows() if r["status"] != "Completed"]
    eng = [r for r in rs if RT.classify(r) == "engineering"]
    for r in eng:
        reason = DECIDED.get(r["id"])
        if not reason:
            problems.append(f"{r['id']} is open engineering with no recorded reason")
            reason = "NO REASON RECORDED"
        L.append(f"- {r['id']}: {r['what'][:120]} -- {reason}")
    cls = Counter(RT.classify(r) for r in rs)
    L += ["", "Open rows by what they wait for: " + ", ".join(f"{k} {v}" for k, v in sorted(cls.items())) + ".", ""]
    return "\n".join(L) + "\n", problems


if __name__ == "__main__":
    text, problems = build()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("engineering audit " + ("current" if ok else "OUT OF DATE: run tools/plans/engineering_audit.py") + ("; " + "; ".join(problems) if problems else ""))
        sys.exit(0 if ok and not problems else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT).as_posix(), problems)
