"""Rebuild docs/plans/milestones.md from the step files and check step references.

Usage: task plans-index   (exit 1 if a step references a step ID that doesn't exist)
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

PLANS = Path(__file__).resolve().parents[2] / "docs" / "plans"
STEP_ID = re.compile(r"\b(p[0-2]-[a-z0-9-]+?-s\d{2})\b")


def main() -> int:
    steps = {}  # id -> (path, title, milestone, approved)
    for path in sorted(PLANS.glob("p*/p*-*/steps/*.md")):
        text = path.read_text(encoding="utf-8")
        sid = STEP_ID.search(path.name).group(1)
        title = text.splitlines()[0].split(" — ", 1)[-1]
        m = re.search(r"^Milestone: \*\*(.+?)\*\*", text, re.M)
        ms = m.group(1) if m else "M1 Walking skeleton 1" if "Walking skeleton 1" in text else "Unassigned"
        steps[sid] = (path, title, ms, path.name.startswith("✅"))

    broken = sorted({(sid, ref) for sid, (p, *_ ) in steps.items()
                     for ref in STEP_ID.findall(p.read_text(encoding="utf-8")) if ref not in steps})

    by_ms = defaultdict(list)
    for sid, (p, title, ms, ok) in steps.items():
        by_ms[ms].append((sid, p, title, ok))

    out = ["# Milestones — all steps", "",
           "_Generated by `task plans-index` from the step files — do not edit by hand._", "",
           f"**{len(steps)} steps** · **{sum(s[3] for s in steps.values())} approved** · {len(by_ms)} milestones", ""]
    for ms in sorted(by_ms, key=lambda s: int(re.match(r"M(\d+)", s).group(1)) if s.startswith("M") else 99):
        rows = sorted(by_ms[ms])
        out += [f"## {ms} ({len(rows)})", "", "| Step | Title | Status |", "|---|---|---|"]
        out += [f"| [{sid}]({p.relative_to(PLANS).as_posix().replace(' ', '%20')}) | {title} | {'✅' if ok else '⬜'} |"
                for sid, p, title, ok in rows]
        out.append("")
    (PLANS / "milestones.md").write_text("\n".join(out), encoding="utf-8")

    print(f"{len(steps)} steps in {len(by_ms)} milestones → docs/plans/milestones.md")
    for sid, ref in broken:
        print(f"  BROKEN: {sid} references unknown step {ref}")
    return 1 if broken else 0


if __name__ == "__main__":
    sys.exit(main())
