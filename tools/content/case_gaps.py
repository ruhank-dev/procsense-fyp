"""Writes docs/research/case_content_gaps.md: for each P0 case, what the walkthrough provides and what a full playable case file still needs.

    uv run --project tools tools/content/case_gaps.py            # rewrite the file
    uv run --project tools tools/content/case_gaps.py --check    # fail if it is out of date (CI)

The 'found in the story' columns are an indicative keyword reading of content/case_seeds.csv, not a clinical judgement. Nothing is invented to fill a gap:
the missing content has to come from the clinician (or the owner has to say explicitly that plausible synthetic content may be authored for review).
"""
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "research" / "case_content_gaps.md"

NEEDS = [  # (what a full case file needs, keywords that suggest the story contains it)
    ("identity (name, age, DOB, MRN, wristband)", r"\b(Mr|Mrs|Ms|Miss)\b.*\b\d{2}\b"),
    ("history with hidden facts and when each is disclosed", r"\b(history|ask|asked|says|took|last (food|drink)|allerg)"),
    ("vital signs", r"\b(HR|heart rate|BP|SpO2|RR)\b"),
    ("examination findings", r"\b(exam|tender|Murphy|guarding|rebound|jaundice|yellow)\b"),
    ("results with flag, comment and previous values", r"\b(WBC|CRP|bilirubin|Hb|HbA1c|potassium|creatinine|INR|lactate)\b"),
    ("imaging report", r"\b(ultrasound|CT|MRCP|X-ray)\b"),
    ("problems and the expected decision at each decision point", r"\b(postpone|proceed|defer|senior|decision|ERCP|emergency)\b"),
    ("expected end state", r"\b(postponed|ready for incision|redirect|safe but delayed|safety failure|READY FOR INCISION)\b"),
    ("debrief block", r"\bdebrief\b"),
]
ALWAYS_MISSING = ["disclose_on rules for every hidden fact", "previous values for every result", "lab comments and sample-quality flags", "the debrief block", "an explicit expected end state"]


def build() -> str:
    with open(ROOT / "content" / "case_seeds.csv", encoding="utf-8", newline="") as f:
        seeds = [r for r in csv.DictReader(f) if r["tier"] == "P0"]
    lines = [
        "<!-- generated by tools/content/case_gaps.py - do not edit; run it again after content/case_seeds.csv changes -->",
        "# Case content gaps (P0 cases)",
        "",
        "The walkthrough describes each case as a story. `content/case_seeds.csv` keeps those stories word for word, and `content/case_measurements.csv` /",
        "`content/case_timelines.csv` keep the tables the book prints for its example patients. A **full playable case file** (p0-medical-research-data s10 to s12,",
        "p0-case-library) needs more than that. Nothing below is invented: it has to come from the clinician, or the owner must say that plausible synthetic content",
        "may be authored for clinician review.",
        "",
        "The 'in the story' columns are a keyword reading, not a clinical judgement (yes = the story mentions it; it may still be incomplete).",
        "",
        "| Case | Walkthrough label | Story length (words) | Playable case file | " + " | ".join(n.split(" (")[0].split(" with")[0] for n, _ in NEEDS) + " |",
        "|---|---|---|---|" + "|".join("---" for _ in NEEDS) + "|",
    ]
    for r in seeds:
        text = r["v_text"]
        cells = ["yes" if re.search(rx, text, re.I) else "**no**" for _, rx in NEEDS]
        built = "yes" if (ROOT / "content" / "case_files" / f"{r['case_id']}.json").exists() else "**no**"
        lines.append(f"| {r['case_id']} | {r['wt_label']} | {len(text.split())} | {built} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "## Status (10 October 2026)",
        "",
        "The owner asked for all case content to be authored (synthetic, no doses, checked against reliable sources). The **17 P0 cases now have playable case files** in `content/case_files/`",
        "(schema `content/schema/case_file.schema.json`, built by `tools/content/build_case_files.py` from `tools/content/cases/`, checked in CI): history with when each fact is disclosed,",
        "examination, results with flag, comment, quality and previous values, scores, ranked problems, decisions with correct and wrong options, end state, correct / incorrect / missed /",
        "recovery paths and the debrief. Every item says whether the book states it or it was authored; authored detail cites one register row per case (`content/case_files_authoring.csv`).",
        "",
        "Still open:",
        "",
        "- The Core loader reads only the Steps 1 to 3 card (`content/cases/*.json`); reading the case files is an engine step (p0-case-library s01). The case files are the format decision: a separate file per case, the card kept for what Core already loads.",
        "- The scenario cards SC-1 to SC-20 and the non-P0 variants (for example S1-I, S1-K, S2-E, S2-H) have stories only; their picture results are mapped (`content/case_imaging.csv`) but no case file is written for them.",
        "- The named clinician should confirm the authored detail and the 'proposed' picture results before any assessment use.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print("docs/research/case_content_gaps.md is out of date: run `uv run --project tools tools/content/case_gaps.py` and commit it")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
