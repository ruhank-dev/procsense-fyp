"""Writes docs/research/image_review_pack.md: every image with its report, for the clinician to approve or reject (ADR-0003 gate).

    uv run --project tools tools/content/image_review_pack.py            # rewrite
    uv run --project tools tools/content/image_review_pack.py --check    # fail if out of date (CI)

Nothing here is approval. Each row has an empty decision column the clinician fills in; an image only leaves DRAFT through a recorded approval in its index entry.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "research" / "image_review_pack.md"
SETS = [("Ultrasound", "content/images", "content/imaging_reports.json"), ("ECG rhythm strips", "content/ecg", "content/ecg_reports.json"),
        ("Chest X-ray", "content/cxr", "content/cxr_reports.json"),
        ("CT, MRI and MRCP", "content/xsec", "content/xsec_reports.json")]


def build() -> str:
    lines = ["# Image and report review pack", "",
             "Generated by `tools/content/image_review_pack.py`; do not edit. Every picture below is DRAFT. A picture is shown to a trainee only after a clinician approves it "
             "(ADR-0003). Please check: (1) the picture really shows the finding named; (2) the report says only what the picture supports; (3) for synthetic pictures, that the "
             "teaching simplification is acceptable. Approvals are recorded per picture in `content/image_approvals.json` (tied to the exact file and report text, so an edit loses its approval).", ""]
    total = 0
    approved = 0
    for title, folder, rep in SETS:
        images = {i["id"]: i for i in json.loads((ROOT / folder / "index.json").read_text(encoding="utf-8"))["images"]}
        reports = json.loads((ROOT / rep).read_text(encoding="utf-8"))["reports"]
        lines += [f"## {title} ({len(reports)})", "", "| Image | Finding | Kind | Source | Report | Status |", "|---|---|---|---|---|---|"]
        for r in reports:
            i = images[r["image_id"]]
            kind = "synthetic (generated)" if i["synthetic"] else "real"
            src = f"{i['source']['dataset']}, {i['source']['class']}, {i['licence']}" if i["source"] else f"{i['generator']['name']} seed {i['generator']['seed']}"
            lines.append(f"| `{folder}/{i['file']}` | {r['finding_code']} | {kind} | {src} | {r['text']} | {i['status']}{' (' + i['approval']['by'] + ', ' + i['approval']['date'] + ')' if i.get('approval') else ''} |")
            approved += i["status"] != "DRAFT"
            total += 1
        lines.append("")
    lines.insert(2, f"**{total} image and report pairs, {approved} approved.**")
    lines.insert(3, "")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    text = build()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            print("docs/research/image_review_pack.md is out of date: run `uv run --project tools tools/content/image_review_pack.py`")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
