"""Generates docs/research/traceability.md: every part of the walkthrough -> the content files and source-register rows built from it.

    uv run --project tools tools/content/trace.py            # rewrite docs/research/traceability.md
    uv run --project tools tools/content/trace.py --check    # fail if the file is out of date or a part is unaccounted for (what CI runs)

A part counts as MAPPED when at least one register row cites it AND at least one content file uses such a row.
Anything else must be listed in tools/content/trace_status.json as either
  "planned"  -> the plan step that will build it (the step file must exist), or
  "not used" -> with the reason.
A part that is none of these fails the check (plan test T-WT1).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from checks import load_register  # noqa: E402
from extract_walkthrough import extract  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
CONTENT = ROOT / "content"
REGISTER = ROOT / "docs" / "research" / "source_register.csv"
STATUS = Path(__file__).resolve().parent / "trace_status.json"
OUT = ROOT / "docs" / "research" / "traceability.md"
PLANS = ROOT / "docs" / "plans"

ONE = r"(?:\d+B?|[A-I])"
# "Part 12", "Parts F and G", "Parts 4, 17"
PART_LIST = re.compile(rf"\bParts?\s+({ONE}(?:\s*(?:,|and|&)\s*{ONE})*)\b")
STEP_REF = re.compile(r"\bStep\s+\d+\b")
SR_ID = re.compile(r"\bSR-\d{4}\b")
SKIP_DIRS = {"schema", "_extract"}


def parts_in(ref: str) -> set[str]:
    """Part ids a register 'walkthrough_ref' points at: 'WT Part 12 Example Patient A' -> {12}; 'Part 11 Step 2; Part 12' -> {11, 12}."""
    found = set()
    for group in PART_LIST.findall(ref):
        found.update(re.findall(ONE, group))
    if STEP_REF.search(ref):
        found.add("11")   # the 15 steps are Part 11
    return found


def content_files() -> list[Path]:
    out = []
    for p in sorted(CONTENT.rglob("*")):
        rel = p.relative_to(CONTENT).parts
        if p.is_file() and p.suffix in (".json", ".csv") and not (set(rel[:-1]) & SKIP_DIRS) and p.name != "vectors.json":
            out.append(p)
    return out


def build() -> tuple[list[dict], list[str]]:
    register = load_register(REGISTER)
    rows_by_part: dict[str, set[str]] = {}
    for rid, row in register.items():
        for part in parts_in(row.get("walkthrough_ref", "")):
            rows_by_part.setdefault(part, set()).add(rid)

    files_by_row: dict[str, set[str]] = {}
    for f in content_files():
        for rid in set(SR_ID.findall(f.read_text(encoding="utf-8"))):
            files_by_row.setdefault(rid, set()).add(f.relative_to(ROOT).as_posix())

    status = json.loads(STATUS.read_text(encoding="utf-8"))
    problems: list[str] = []
    seen: set[str] = set()
    table = []
    for part in extract()["parts"]:
        pid = part["id"]
        if pid in seen:
            continue   # Part D has two headings
        seen.add(pid)
        rows = sorted(rows_by_part.get(pid, set()))
        files = sorted({f for r in rows for f in files_by_row.get(r, set())})
        entry = status.get(pid, {})
        note = entry.get("note", "")
        if rows and files:
            kind, detail = "mapped", note
        elif entry.get("status") == "planned":
            step = entry.get("step", "")
            if not list(PLANS.rglob(f"*{step}-*.md")) or not step:
                problems.append(f"part {pid}: planned step '{step}' does not exist in docs/plans")
            kind, detail = "planned", step
        elif entry.get("status") == "not used":
            if not entry.get("reason"):
                problems.append(f"part {pid}: 'not used' needs a reason")
            kind, detail = "not used", entry.get("reason", "")
        else:
            problems.append(f"part {pid} ({part['title']}) is not mapped, planned or marked 'not used' in tools/content/trace_status.json")
            kind, detail = "UNACCOUNTED", ""
        if rows and files and entry.get("status") in ("planned", "not used"):
            problems.append(f"part {pid} is now mapped: remove it from trace_status.json (keep a 'note' if only part of it is built)")
        table.append({"id": pid, "title": part["title"], "kind": kind, "detail": detail, "files": files, "rows": rows})
    extra = sorted(set(status) - seen)
    problems += [f"trace_status.json lists part '{p}', which the walkthrough does not have" for p in extra]
    return table, problems


def render(table: list[dict]) -> str:
    done = sum(1 for t in table if t["kind"] == "mapped")
    lines = [
        "<!-- generated by tools/content/trace.py - do not edit; run `task content-trace` -->",
        "# Traceability: walkthrough part -> content -> register",
        "",
        f"{len(table)} parts of the walkthrough; **{done} mapped** to content, {sum(1 for t in table if t['kind'] == 'planned')} planned in a step, "
        f"{sum(1 for t in table if t['kind'] == 'not used')} not used (with the reason).",
        "",
        "| Part | Title | Status | Content files | Register rows | Planned in / reason / note |",
        "|---|---|---|---|---|---|",
    ]
    for t in table:
        title = re.sub(r"^(Part \d+B?|PART [A-I]) — ", "", t["title"]).replace("|", "/")[:70]
        files = "<br>".join(t["files"]) if t["files"] else "-"
        rows = ", ".join(t["rows"][:6]) + (f" (+{len(t['rows']) - 6})" if len(t["rows"]) > 6 else "") if t["rows"] else "-"
        lines.append(f"| {t['id']} | {title} | {t['kind']} | {files} | {rows} | {t['detail'].replace('|', '/')} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    table, problems = build()
    text = render(table)
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            problems.append("docs/research/traceability.md is out of date: run `task content-trace` and commit it")
    else:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.relative_to(ROOT)}")
    for p in problems:
        print("  - " + p)
    mapped = sum(1 for t in table if t["kind"] == "mapped")
    print(f"{len(table)} parts: {mapped} mapped, {sum(1 for t in table if t['kind'] == 'planned')} planned, {sum(1 for t in table if t['kind'] == 'not used')} not used" + ("" if not problems else f"; {len(problems)} problem(s)"))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
