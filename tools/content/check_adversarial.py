"""Checks the adversarial decision blocks against the case library and writes the page that lists where each applies (DT-197): `uv run --project tools tools/content/check_adversarial.py [--check]`.

A block (content/adversarial/blocks.json) is a decision whose WRONG option looks like the right thing to do, and the ANCHOR: the fact in a case that shows why it is wrong. The block is only fair to a case that holds its anchor,
so for every block this tool finds the cases whose own content holds it (the allergies, the history answers or the results, searched for the words of the anchor) and fails when:
  * a block has no case that holds its anchor (a trap nobody can be fairly given),
  * the wrong option is the right option, or either is empty or very long (the options must read alike),
  * the consequence names nothing of the anchor (the trainee would not learn why),
  * ids repeat, or the status is not "awaiting_review" (a block is never presented as clinician-approved by this tool).
The page docs/research/adversarial_blocks.md lists, per block, the cases that hold the anchor, for a clinician to read. Nothing here claims clinical review.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BLOCKS = ROOT / "content" / "adversarial" / "blocks.json"
PAGE = ROOT / "docs" / "research" / "adversarial_blocks.md"
MAX_WORDS = 40


def cases() -> dict[str, dict]:
    return {d["id"]: d for d in (json.loads(p.read_text(encoding="utf-8")) for p in sorted((ROOT / "content" / "case_files").glob("*.json")))}


def text_of(case: dict, where: str) -> str:
    if where == "allergies":
        return " ".join((a.get("allergen", "") + " " + str(a.get("reaction", ""))) if isinstance(a, dict) else str(a) for a in case["allergies"]) + " " + case.get("allergy_answer", "")
    if where == "history":
        return " ".join(h["answer"] for h in case["history"]) + " " + case["presentation"].get("summary", "") if isinstance(case.get("presentation"), dict) else " ".join(h["answer"] for h in case["history"])
    if where == "identity":
        i = case.get("identity", {})
        return f"age {i.get('age', '')} sex {i.get('sex', '')} {i.get('occupation', '')}"
    if where == "problems":
        return " ".join(p["label"] + " " + p.get("why", "") for p in case["problems"])
    if where == "last_food":
        return " ".join(h["answer"] for h in case["history"] if h["topic"] == "last_food")
    if where == "results":
        return " ".join(r["test"] + " " + str(r.get("value", "")) for r in case["results"])
    raise ValueError(where)


def holders(block: dict, all_cases: dict[str, dict]) -> list[str]:
    pat = re.compile(block["anchor"]["match"], re.I)
    return sorted(cid for cid, c in all_cases.items() if pat.search(text_of(c, block["anchor"]["in"])))


def problems(data: dict, all_cases: dict[str, dict]) -> list[str]:
    out, seen = [], set()
    if data.get("status") != "awaiting_review":
        out.append("the file must say status awaiting_review: no clinician has reviewed these blocks")
    for b in data["blocks"]:
        if b["id"] in seen:
            out.append(f"{b['id']}: id repeated")
        seen.add(b["id"])
        if not holders(b, all_cases):
            out.append(f"{b['id']}: no case holds the anchor {b['anchor']}")
        if not b["wrong"].strip() or not b["right"].strip() or b["wrong"].strip().lower() == b["right"].strip().lower():
            out.append(f"{b['id']}: the wrong and the right option must be different and not empty")
        if max(len(b["wrong"].split()), len(b["right"].split())) > MAX_WORDS or abs(len(b["wrong"].split()) - len(b["right"].split())) > 18:
            out.append(f"{b['id']}: the two options must be of similar and short length (at most {MAX_WORDS} words)")
        anchor_words = {w for w in re.findall(r"[a-z]{4,}", b["anchor"]["match"].lower())} | {w for w in re.findall(r"[a-z]{5,}", b["title"].lower())}
        if not anchor_words & set(re.findall(r"[a-z]{4,}", b["consequence"].lower())):
            out.append(f"{b['id']}: the consequence names nothing of the anchor")
        if not b.get("source"):
            out.append(f"{b['id']}: no source")
    return out


def page(data: dict, all_cases: dict[str, dict]) -> str:
    L = ["# Adversarial decision blocks (DT-197)", "", "_Generated by `tools/content/check_adversarial.py`; do not edit by hand._", "",
         "**Status: not reviewed by a clinician.** Each block is a decision whose wrong option looks right, with the fact in the case that shows why it is wrong. It is offered only to a case that holds that fact. "
         "The texts were written by an AI assistant from the published guidance named in each row. A clinician is asked to confirm or change them (`docs/research/clinician_signoff.md`).", "",
         f"{len(data['blocks'])} blocks. Checks that pass: every block has at least one case that holds its anchor, the two options differ and are of similar length, the consequence names the anchor, and every block is marked awaiting review.", ""]
    for b in data["blocks"]:
        h = holders(b, all_cases)
        L += [f"## {b['id']}: {b['title']}", "", f"- Decision: {b['prompt']}", f"- Looks right, is wrong: {b['wrong']}", f"- Right: {b['right']}", f"- Why wrong (the consequence): {b['consequence']}",
              f"- Anchor: {b['anchor']['in']} matching `{b['anchor']['match']}`; held by {len(h)} cases: {', '.join(h[:12])}{' ...' if len(h) > 12 else ''}", f"- Source: {b['source']}", ""]
    return "\n".join(L) + "\n"


def main(argv: list[str]) -> int:
    data = json.loads(BLOCKS.read_text(encoding="utf-8"))
    all_cases = cases()
    bad = problems(data, all_cases)
    if bad:
        print("FAIL\n  " + "\n  ".join(bad))
        return 1
    text = page(data, all_cases)
    if "--check" in argv:
        if not PAGE.exists() or PAGE.read_text(encoding="utf-8") != text:
            print("FAIL  docs/research/adversarial_blocks.md is out of date; run tools/content/check_adversarial.py")
            return 1
        print(f"adversarial blocks: {len(data['blocks'])} blocks, each held by at least one case; page current")
        return 0
    PAGE.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {PAGE.relative_to(ROOT)} ({len(data['blocks'])} blocks)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
