"""Builds content/sources/citations.json: the short citation of every row of the source register (docs/research/source_register.csv), so the headset can show where a rule or a
figure comes from (DT-261). The debrief's evidence drawer names an item's source by its register ID (SR-0000); the register itself is a research document that does not ship in the APK,
this table does. A citation is the source's name and, when the register gives one, where in it ("ProcSense Medical Walkthrough v5.1, 'Who:' line").

    uv run --project tools tools/content/build_citations.py            # write the file
    uv run --project tools tools/content/build_citations.py --check    # fail if it is out of date, or a debrief source the content names is missing from the register
"""
from __future__ import annotations

import csv
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REGISTER = ROOT / "docs" / "research" / "source_register.csv"
CONTENT = ROOT / "content"
OUT = CONTENT / "sources" / "citations.json"
ID = re.compile(r"\bSR-\d{4}\b")


def citation(row: dict) -> str:
    name = (row.get("source_name") or "").strip()
    where = (row.get("source_location") or "").strip()
    return name + (", " + where if where and where not in name else "") if name else where


def build() -> dict:
    with open(REGISTER, encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    cites = {r["id"].strip(): citation(r) for r in rows if ID.fullmatch(r["id"].strip()) and citation(r)}
    return {"note": "Generated by tools/content/build_citations.py from docs/research/source_register.csv; do not edit by hand. The headset shows these for the register IDs the debrief names (DT-261).",
            "citations": dict(sorted(cites.items()))}


def named_by_debrief() -> set[str]:
    """The register IDs the debrief can name: the scoring rubric's refs and the lateness sources written in Core."""
    ids = set(ID.findall((CONTENT / "scoring" / "rubric.json").read_text(encoding="utf-8")))
    ids |= set(ID.findall((ROOT / "src" / "ProcSense.Core" / "Scoring" / "Scorer.cs").read_text(encoding="utf-8")))
    return ids


def main(argv: list[str]) -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    table = build()
    text = json.dumps(table, ensure_ascii=False, indent=1) + "\n"
    missing = sorted(named_by_debrief() - set(table["citations"]))
    if missing:
        print(f"{len(missing)} source(s) the debrief can name have no citation in the register: " + ", ".join(missing[:20]))
        return 1
    n = len(table["citations"])
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            print("content/sources/citations.json is out of date: run tools/content/build_citations.py and commit it")
            return 1
        print(f"citations up to date: {n} register rows; every source the debrief can name has one")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {n} citations; every source the debrief can name has one")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
