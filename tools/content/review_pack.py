"""Writes docs/research/review_pack.md (p0-medical-research-data s17): what a medical reviewer would look at, in one place, with the content hash it applies to.

    uv run --project tools tools/content/review_pack.py            # rewrite (also writes docs/research/review_pack_type_c.csv)
    uv run --project tools tools/content/review_pack.py --check    # fail if out of date (CI)

Everything is computed from the committed files: the source register, issues.md, clinical_verification.md, the case files, the picture library, the equipment data and the content manifest.
It lists what is open or proposed so nothing is hidden; it does not itself approve anything (the owner states that the clinician approves everything, 10 October 2026).
"""
from __future__ import annotations

import csv
import io
import json
import re
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import content_manifest as cm  # noqa: E402
import equipment_data as eq  # noqa: E402
import imaging_library as lib  # noqa: E402

OUT = ROOT / "docs" / "research" / "review_pack.md"
TYPE_C = ROOT / "docs" / "research" / "review_pack_type_c.csv"


def rows(path: Path) -> list[dict]:
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def short(s: str, n: int = 150) -> str:
    s = re.sub(r"\s+", " ", s).strip()
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


def issues() -> list[dict]:
    out = []
    for line in (ROOT / "docs" / "research" / "issues.md").read_text(encoding="utf-8").split("\n"):
        if re.match(r"^\| (ISS|WT)-", line):
            c = [x.strip() for x in line.strip().strip("|").split("|")]
            if len(c) >= 6:
                out.append({"id": c[0], "issue": c[1], "who": c[4], "status": c[-1]})
    return out


def verification() -> list[dict]:
    out = []
    for line in (ROOT / "docs" / "research" / "clinical_verification.md").read_text(encoding="utf-8").split("\n"):
        m = re.match(r"^\| (V-\d\d) \| (.*?) \| (.*?) \| (primary|secondary|recalled) \| (.*) \|$", line)
        if m:
            out.append({"id": m.group(1), "claim": m.group(2), "level": m.group(4), "result": m.group(5)})
    return out


def build() -> tuple[str, str]:
    man = cm.build()
    reg = rows(ROOT / "docs" / "research" / "source_register.csv")
    ev = Counter((r["evidence_type"], r["status"]) for r in reg)
    iss = issues()
    open_iss = [i for i in iss if i["status"].lower().startswith("open")]
    ver = verification()
    cases = [json.loads(p.read_text(encoding="utf-8")) for p in sorted((ROOT / "content" / "case_files").glob("*.json"))]
    lb = lib.library()
    ci_rows = rows(ROOT / "content" / "case_imaging.csv")
    wi_rows = rows(ROOT / "content" / "whatif_imaging.csv")
    proposed = [r for r in ci_rows if r["d_basis"] == "proposed"]
    typec = [r for r in reg if r["evidence_type"] == "C"]
    open_dims = sum(1 for it in eq.ITEMS.values() for d in it["dims"] if d["level"] == "open")
    all_dims = sum(len(it["dims"]) for it in eq.ITEMS.values())

    L = ["# Review pack for the medical professional", "",
         "Generated by `tools/content/review_pack.py`; do not edit. It collects, in one place, what is open, proposed or authored, so a reviewer can use their time where it matters. "
         "**Nothing here approves anything**: the owner states that the clinician approves everything (10 October 2026) and the clinician is not named; this pack is what the named clinician "
         "would look at if a second check is wanted before any assessment use. Reading order for a 45-minute review: sections 1, 2, 3 (about 25 minutes), then 4 to 6 as time allows.", "",
         f"**Applies to content hash `{man['content_hash'][:16]}…`** ({man['files']} files, {man['bytes'] / 1e6:.1f} MB; `content/manifest.json`).", "",
         "## 1. Open issues (conflicts between sources, never resolved silently)", ""]
    L += ["| ID | Issue | Who decides | Status |", "|---|---|---|---|"] + [f"| {i['id']} | {short(i['issue'], 170)} | {short(i['who'], 90)} | {i['status']} |" for i in open_iss] if open_iss else ["None open."]
    L += ["", f"Closed issues: {len(iss) - len(open_iss)} of {len(iss)} (full text and decisions: `docs/research/issues.md`).", "",
          "## 2. Guideline claims behind the case files, and how each was checked", "",
          "| ID | Claim | Level | Result |", "|---|---|---|---|"] + [f"| {v['id']} | {short(v['claim'], 140)} | {v['level']} | {short(v['result'], 120)} |" for v in ver]
    lv = Counter(v["level"] for v in ver)
    L += ["", f"{len(ver)} claims: {lv['primary']} checked against the guideline page itself, {lv['secondary']} against two or more independent published summaries (the guideline text was not opened), {lv['recalled']} recalled. "
          "Details and links: `docs/research/clinical_verification.md`.", "",
          "## 3. What was authored (the book does not say it)", "",
          "Each case file marks every item as `book` or `authored`; authored items cite one register row per case (`content/case_files_authoring.csv`) and are checked by the case-file validator (NEWS2 recomputed from the verified table, flags against the normal ranges and critical limits, no doses).", "",
          "| Case | End state | Book items | Authored items | Decisions | Problems | Picture results to confirm |", "|---|---|---|---|---|---|---|"]
    for c in cases:
        items = c["history"] + c["observations"] + c["examination"] + c["results"] + c["scores"]
        b = sum(1 for i in items if i["origin"] == "book")
        a = sum(1 for i in items if i["origin"] == "authored")
        n_prop = sum(1 for r in proposed if r["case_id"] == c["id"])
        L.append(f"| {c['id']} | {c['expected_end_state']}{' (variants: ' + ', '.join(f'{k} {v}' for k, v in c.get('variant_end_states', {}).items()) + ')' if c.get('variant_end_states') else ''} | {b} | {a} | {len(c['decisions'])} | {len(c['problems'])} | {n_prop} |")
    L += ["", f"Picture results: {len(ci_rows)} case rows ({len(proposed)} 'proposed': the story names the test but not its result) and {len(wi_rows)} what-if rows (the cause chooses the finding) in `content/case_imaging.csv` and `content/whatif_imaging.csv`.", "",
          "## 4. Institution-specific values (evidence type C) with the default chosen", "",
          f"{len(typec)} register rows are type C (the book gives a value that depends on local practice, for example lab bands). They are listed with the value in use in `docs/research/review_pack_type_c.csv`; "
          "the 15 institutional decisions of Part I were closed by the owner on 09 October 2026.", "",
          "## 5. Data derived from datasets (realism)", "",
          "| Output | Source dataset | What it holds |", "|---|---|---|",
          "| `content/physio_noise.csv` | VitalDB | spread and autocorrelation of each vital sign, by variable |",
          "| `content/physio_ecg_templates.csv` | PTB-XL | one averaged beat for sinus rhythm, tachycardia and atrial fibrillation |",
          "| `content/lab_plausibility.csv`, `content/ed_triage_abdominal.csv` | MIMIC-IV demo and ED demo | percentiles only; for tests, not shipped as data |",
          "| `content/drug_label_safety.csv` | openFDA labels | contraindication and boxed-warning wording, doses removed |", "",
          "Cards: `docs/research/datasets/`; register: `docs/research/dataset_register.csv`.", "",
          "## 6. Pictures", "",
          f"{sum(r['pictures'] for r in lb)} pictures with matching reports over {len(set(r['test'] for r in lb))} tests ({len(lb)} results, at least 4 pictures per result), plus written-only results for the pregnancy test, dipstick and blood sample appearance. "
          "Real pictures (UIdataGB, NIH ChestX-ray14, AMOS, PTB-XL) keep their licence and attribution; every synthetic picture carries the visible mark and names its generator and real base. "
          "The per-picture review table is `docs/research/image_review_pack.md`; approvals are owner-attested (`content/image_approvals.json`), at training level only.", "",
          "## 7. Equipment sheets", "",
          f"53 sheets in `docs/research/equipment`: {all_dims - open_dims} of {all_dims} dimension rows have a source (two read in a manufacturer data sheet, the rest manufacturer specifications on catalogue pages or standards), {open_dims} are open (no source found, placeholders until one is). "
          "Pole, wristband, dipstick and cassette sizes are among the open ones.", "",
          "## 8. Validation summary", "",
          "CI (`task ci`, also run by the pre-push hook) checks, among others: source register and every content table against the book (verbatim) and the official quotes; NEWS2 and sepsis tables against the RCP and NICE pages; "
          "53 case files (17 P0, 16 P1, 20 P2: schema, NEWS2, flags, no doses; also loaded by Core's own strict loader); every picture against its recorded hash, licence, attribution and the visible mark; the imaging library (clean and problem results, at least 4 pictures each, "
          "every result reachable from a case or a what-if); 53 equipment sheets; the content manifest below. The full list with what each catches is `docs/CI.md`.", "",
          f"Register: {len(reg)} rows. Evidence A (guideline cited by the book): {ev[('A', 'VERIFIED')]} verified, {ev[('A', 'UNVERIFIED')]} still open (checked again on 10 October 2026 and not confirmed, with the reason in each row; see `tools/content/tables/type_a_checks.py`). The rest were verified at the original or in two or more independent summaries, or re-typed D where they are simulator design values; every claim is in section 2. "
          f"B: {ev[('B', 'VERIFIED')]} verified, {ev[('B', 'UNVERIFIED')]} not opened. C: {ev[('C', 'UNVERIFIED')]} institution-specific. D: {ev[('D', 'VERIFIED')]} authored in the walkthrough.", "",
          f"Content package: {man['files']} files; per folder: " + ", ".join(f"{k} {v}" for k, v in man["per_folder"].items()) + f". Content hash: `{man['content_hash']}`.", ""]
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["id", "item", "value", "unit", "walkthrough_ref", "status", "notes"])
    for r in typec:
        w.writerow([r["id"], r["item"], r["value"], r["unit"], r["walkthrough_ref"], r["status"], short(r["notes"], 200)])
    return "\n".join(L) + "\n", buf.getvalue()


def main(argv: list[str]) -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    text, csv_text = build()
    if "--check" in argv:
        bad = [p.name for p, t in ((OUT, text), (TYPE_C, csv_text)) if not p.exists() or p.read_text(encoding="utf-8").replace("\r\n", "\n") != t]
        for b in bad:
            print(f"docs/research/{b} is out of date: run `uv run --project tools tools/content/review_pack.py`")
        return 1 if bad else 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    TYPE_C.write_text(csv_text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines) and {TYPE_C.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
