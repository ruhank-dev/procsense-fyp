"""Builds content/ui/monitor.json: how the bedside monitor alarms and draws its traces (p0-vr-interaction-ui-s04, p0-voice-audio-s05).

The values a monitor shows and their display zones come from Core (content/physio/display_zones.json). This table says which zones alarm on the monitor and at what
priority, how long an acknowledged alarm stays silent, how long the cuff takes to cycle on screen, and the trace speeds. The walkthrough says alarm limits are an
institutional protocol to be confirmed by a clinician (SR-1802), so every value here is a design value for the realism review (p0-evaluation-performance-s06).
The three priorities follow the usual monitor convention (high, medium, low with a distinct tone and repeat rate); that convention is also for the review to confirm.

    uv run --project tools tools/content/build_monitor.py            # write the file
    uv run --project tools tools/content/build_monitor.py --check    # fail if it is out of date or names a zone or vital Core does not publish
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ZONES = ROOT / "content" / "physio" / "display_zones.json"
OUT = ROOT / "content" / "ui" / "monitor.json"

# the vitals the monitor itself measures; the counted and asked ones (breathing, temperature, alertness, pain) are written down, not alarmed
MONITORED = {"spo2": "spo2", "heart_rate": "heart_rate", "systolic_bp": "systolic_bp_low"}

TABLE = {
    "alarms": {
        "monitored": MONITORED,
        "zone_priority": {"emergency": "high", "worry": "medium", "watch": "low"},
        "priorities": {
            "high": {"rank": 3, "symbol": "!!!", "label": "HIGH", "repeat_seconds": 2.5, "pulses": 10},
            "medium": {"rank": 2, "symbol": "!!", "label": "MEDIUM", "repeat_seconds": 6.0, "pulses": 3},
            "low": {"rank": 1, "symbol": "!", "label": "LOW", "repeat_seconds": 16.0, "pulses": 2},
        },
        "silence_seconds": 120,
        "ref": "SR-1802",
    },
    "probe": {"poor_pleth": "Poor signal: check the probe (warm finger, no nail polish, keep still), then re-site it"},
    "nibp": {"cycle_label": "Cuff cycling"},
    "traces": {"sample_hz": 100, "sweep_seconds": 4, "ecg_mm_per_s": 25, "resp_default": 14},
    "text_hz": 10,
}


def build() -> dict:
    zones = json.loads(ZONES.read_text(encoding="utf-8"))
    problems = []
    named = set()
    for vital, parameter in MONITORED.items():
        if parameter not in zones["parameters"]:
            problems.append(f"{vital}: Core has no display zones for '{parameter}'")
        else:
            named |= {r["zone"] for r in zones["parameters"][parameter]["rows"]}
    problems += [f"zone '{z}' is not one Core gives a monitored vital" for z in TABLE["alarms"]["zone_priority"] if z not in named]
    for z, p in TABLE["alarms"]["zone_priority"].items():
        if p not in TABLE["alarms"]["priorities"]:
            problems.append(f"zone {z}: priority {p} is not defined")
    for q in TABLE["probe"]:
        if q not in {a["quality"] for a in zones["artefacts"].values()}:
            problems.append(f"probe quality '{q}' is not one Core publishes")
    if problems:
        raise SystemExit("\n".join(problems))
    return {"note": "Generated by tools/content/build_monitor.py; do not edit by hand. Alarm limits are the display zones in content/physio/display_zones.json; "
                    "the priorities, silence time and cuff label are design values for the clinical realism review (SR-1802: alarm limits are institutional).", **TABLE}


def main(argv: list[str]) -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    text = json.dumps(build(), ensure_ascii=False, indent=1) + "\n"
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            print("content/ui/monitor.json is out of date: run tools/content/build_monitor.py and commit it")
            return 1
        print("monitor table up to date: 3 monitored vitals, 3 alarm priorities, every zone and probe quality is one Core publishes")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
