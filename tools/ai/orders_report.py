"""Writes docs/research/order_mapper_comparison.md from the committed comparison files: `uv run --project tools tools/ai/orders_report.py [--check]` (ADR-0021).

Reads reports/ai/orders-mapper-compare.json, orders-mapper-compare-latency.json, orders-mapper-compare-latency2.json and orders-mapper-compare-v4.json (tools/ai/compare_order_mappers.py) and shows, for every set and mapper, COUNTS with their denominators: orders read back correctly, read back as a wrong item, sent to the menu or asked as a question between two items, non-orders offered as an order,
and the median and 95th percentile of the time per hearing. Every percentage on the page is a count over a stated number (a rate such as 3.7 percent is 2 of 54: the score file keeps the rate rounded to three places and the page recovers the count by multiplying back by the number of orders, which is exact for
these sizes). The model is not deterministic, so two runs of the same mapper on the same set differ by a few sentences; a difference of one or two sentences in one set is within that noise.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
ROOT = Path(__file__).resolve().parents[2]
R = ROOT / "reports" / "ai"
OUT = ROOT / "docs" / "research" / "order_mapper_comparison.md"
FILES = [("orders-mapper-compare.json", "Standard comparison (19 Oct 2026, first run): grammar, single-call predecessor, current mapper"),
         ("orders-mapper-compare-latency.json", "Latency candidates, run 1 (no other GPU work; the orphaned model runners of an earlier experiment were killed first): current and lean"),
         ("orders-mapper-compare-latency2.json", "Latency candidates, run 2: compact and short"),
         ("orders-mapper-compare-v4.json", "Fresh set 4 (scored once, for the standard comparison)"),
         ("orders-mapper-compare-v4-candidates.json", "Set 4 again (a SECOND LOOK: it is no longer untouched), grammar, predecessor, current and the short-prompt candidate")]


def cell(res: dict, key: str, n: int) -> str:
    return f"{round(res[key] * n)}/{n}"


def render() -> str:
    L = ["# Spoken-order mappers on the same sentences, with counts", "",
         "_Generated by `tools/ai/orders_report.py` from `reports/ai/orders-mapper-compare*.json`; do not edit by hand. Synthetic sentences from one author family; not independent. Gate `order_fallback` stays OFF: it needs at least 90 percent correct, at most 5 percent wrong, at most 10 percent of non-orders offered and a 95th percentile of 3 s._", "",
         "Mappers: `grammar` (no model), `legacy` (the single-call mapper of the fourth session), `current` (kind stage, notes, re-ranking, agreement of two readings), `lean` (shorter kind prompt, list-first map prompt, shorter notes, items in a fixed order), `compact` (lean, and only the 8 best-ranked items carry a note), `short` (compact with the shortest prompts and 6 notes).", "",
         "Columns: correct = the first read-back named the right item and intent; wrong = a read-back of another item; menu/question = no read-back (the menu, or a question between two items); offered = non-orders turned into an order read-back. Time is per hearing (grammar plus all model calls).", ""]
    for fname, title in FILES:
        p = R / fname
        if not p.exists():
            continue
        d = json.loads(p.read_text(encoding="utf-8"))
        L += [f"## {title}", "", "| Set | Mapper | Correct | Wrong | Menu or question | Questions (with the right item) | Non-orders offered | Median / p95 (ms) |", "|---|---|---|---|---|---|---|---|"]
        for sname, s in d["sets"].items():
            for m, res in s.items():
                if not isinstance(res, dict) or "orders" not in res:
                    continue
                n, nn = res["orders"], res["non_orders"]
                L.append(f"| {sname} ({n} orders, {nn} non-orders) | {m} | {cell(res, 'correct', n)} | {cell(res, 'wrong', n)} | {cell(res, 'menu', n)} | {res.get('clarify_questions', 0)} ({res.get('clarify_questions_containing_the_right_item', 0)}) | {cell(res, 'false_offer', nn)} | {res['latency_ms_p50']} / {res['latency_ms_p95']} |")
        L.append("")
    prof = sorted(R.glob("orders-latency-profile-*.json"))
    if prof:
        L += ["## Where the time of one hearing goes (16 development orders; `tools/ai/profile_orders.py`)", "", "| Variant | Calls per hearing | Median / p95 hearing (ms) | Kind call (ms, prompt tokens) | Map call (ms, prompt tokens) | Python outside the host calls (ms) |", "|---|---|---|---|---|---|"]
        for p in prof:
            d = json.loads(p.read_text(encoding="utf-8"))
            k, m = d["by_call_type"]["kind"], d["by_call_type"]["map"]
            L.append(f"| {d['label']} | {d['calls_per_hearing']} | {d['hearing_ms_median']} / {d['hearing_ms_p95']} | {k['wall_ms']} ({k['prompt_tokens']:.0f}) | {m['wall_ms']} ({m['prompt_tokens']:.0f}) | {d['python_outside_host_calls_ms_median']} |")
        L += ["", "Reading: nearly all the time is the host evaluating the prompt (about 4 ms a token on the desktop card) plus a few hundred milliseconds of generation; serialization and the network hop are under 2 ms a call and the Python around the calls is 140 ms (it was 266 ms before the grammar skipped fuzzy comparisons that cannot reach the threshold). "
              "Two parallel host slots did not let the host reuse an evaluated list between hearings (the prompt token counts did not fall) and produced a 60 s stall once, so it was dropped. The agreement rule makes about a fifth of the hearings three calls; that tail sets the 95th percentile.", ""]
    return "\n".join(L) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("order mapper comparison page " + ("current" if ok else "OUT OF DATE: run tools/ai/orders_report.py"))
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
