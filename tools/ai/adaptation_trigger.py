"""Is model adaptation justified yet? `uv run --project tools tools/ai/adaptation_trigger.py [--write|--check]` (p2-ai-advanced-simulation-s04 and s05).

Reads content/ai/adaptation_triggers.json (the conditions, the remedies tried, the data counts) and the measured gate content/ai/features.json. For each track it reports every condition as MET or NOT MET and
says `TRIGGER MET` only when all hold. A track whose gate suites all pass has no quality gap, so nothing can justify adapting it. Exit code 0 always for the report; with --check the generated page
docs/research/adaptation_trigger_check.md must equal a fresh run (so a changed gate result or a new remedy forces the page to be regenerated), and a track claiming TRIGGER MET fails the check unless an
experiment record exists in reports/ai/adaptation-experiment.json (it does not, and none has been run: nothing is trained until the trigger is met).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CFG = ROOT / "content" / "ai" / "adaptation_triggers.json"
FEATURES = ROOT / "content" / "ai" / "features.json"
PAGE = ROOT / "docs" / "research" / "adaptation_trigger_check.md"
EXPERIMENT = ROOT / "reports" / "ai" / "adaptation-experiment.json"


def failing_suites(features: dict, ids: list[str]) -> list[dict]:
    out = []
    for fid in ids:
        f = features["features"].get(fid)
        if f is None:
            raise SystemExit(f"adaptation_triggers.json names feature {fid!r}, which content/ai/features.json does not have")
        out += [{"feature": fid, "id": s["id"], "got": s.get("got"), "needs": s.get("needs")} for s in f["suites"] if s["status"] == "FAIL"]
    return out


def image_gap() -> int:
    text = (ROOT / "docs" / "research" / "imaging_gaps.md").read_text(encoding="utf-8")
    table = text.split("## Findings with synthetic pictures only", 1)[1].split("\n## ", 1)[0]
    return len(re.findall(r"^\| [A-Z]+-[A-Z0-9-]+ \|", table, flags=re.M))


def evaluate(cfg: dict, features: dict) -> list[dict]:
    out = []
    for t in cfg["tracks"]:
        gap = failing_suites(features, t["features"]) if t["features"] else []
        n_img = image_gap() if t.get("gap_file") else 0
        has_gap = bool(gap) or n_img > 0
        untried = [r["name"] for r in t["remedy_ladder"] if not r["tried"]]
        conds = [
            ("a measured quality gap", has_gap, (f"{len(gap)} failing suite(s): " + ", ".join(g["id"] for g in gap)) if gap else (f"{n_img} findings with synthetic pictures only" if n_img else "every gate suite of the track passes")),
            ("every remedy on the ladder tried", not untried, "all tried" if not untried else "not yet tried: " + "; ".join(untried)),
            (f"at least {t['min_training_examples']} permitted training examples that are not the model's own output", t["permitted_training_examples"] >= t["min_training_examples"], f"{t['permitted_training_examples']} ({t['training_source']})"),
            ("a held-out evaluation set that shares nothing with the training data", bool(t["heldout_available"]), "yes" if t["heldout_available"] else "no"),
            ("a compute budget that does not take the card from live use", t["compute_free_gpu_hours"] > 0, f"{t['compute_free_gpu_hours']} free GPU hours ({t['compute_note']})"),
        ]
        out.append({"id": t["id"], "plan": t["plan"], "conditions": conds, "met": all(ok for _, ok, _ in conds)})
    return out


def render(results: list[dict]) -> str:
    lines = ["# Model adaptation: the trigger check (generated)", "",
             "Generated by `tools/ai/adaptation_trigger.py` from `content/ai/adaptation_triggers.json` and the measured gate `content/ai/features.json`; do not edit by hand. "
             "It replaces the hand-written numbers that were here on 18 October 2026 before the gaps were closed. No model was fine-tuned and no generator was trained.", ""]
    for r in results:
        lines += [f"## {r['id']} ({r['plan']}): {'TRIGGER MET' if r['met'] else 'trigger not met'}", "", "| Condition | Holds | Evidence |", "|---|---|---|"]
        lines += [f"| {name} | {'yes' if ok else 'no'} | {ev} |" for name, ok, ev in r["conditions"]]
        lines.append("")
    lines += ["A track starts only when every row says yes. Today the language models have no failing quality suite, the picture track lacks licensed data and a free card, and no track has the permitted training examples a fine-tune would need. "
              "Rerun after any change to the gate, the ladder or the data counts.", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    cfg = json.loads(CFG.read_text(encoding="utf-8"))
    results = evaluate(cfg, json.loads(FEATURES.read_text(encoding="utf-8")))
    text = render(results)
    if "--check" in argv:
        bad = []
        if not PAGE.exists() or PAGE.read_text(encoding="utf-8") != text:
            bad.append("docs/research/adaptation_trigger_check.md is out of date: run tools/ai/adaptation_trigger.py --write")
        if any(r["met"] for r in results) and not EXPERIMENT.exists():
            bad.append("a trigger is met but there is no experiment record (reports/ai/adaptation-experiment.json): run the smallest reversible experiment before anything else")
        for b in bad:
            print("FAIL " + b)
        print("adaptation trigger check " + ("FAILED" if bad else "current: " + ", ".join(f"{r['id']} {'MET' if r['met'] else 'not met'}" for r in results)))
        return 1 if bad else 0
    print(text)
    if "--write" in argv:
        PAGE.write_text(text, encoding="utf-8", newline="\n")
        print("wrote", PAGE.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
