"""Synthetic dataset cards: refuse the incomplete, index the rest (p1-evaluation-s01, plan tests T-SD1 and T-SD4).

    uv run --project tools tools/synth/publish.py            # write docs/research/datasets/synthetic/README.md (the card index)
    uv run --project tools tools/synth/publish.py --check    # fail if a card is incomplete, a generator or file is missing, a row count is wrong, or the index is out of date (CI)

A card (docs/research/datasets/synthetic/SD-nnn-*.yaml, schema tools/synth/card_schema.json) says what a synthetic dataset is for, what made it, from what, under which constraints, how it was checked, who
reviewed it, what labels it has and what reads it. The check opens every file the card names and compares the row counts the card states with the files, so a card cannot drift from its data.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import jsonschema
import yaml

ROOT = Path(__file__).resolve().parents[2]
CARDS = ROOT / "docs" / "research" / "datasets" / "synthetic"
SCHEMA = ROOT / "tools" / "synth" / "card_schema.json"
INDEX = CARDS / "README.md"


def load_cards() -> list[dict]:
    return [yaml.safe_load(p.read_text(encoding="utf-8")) for p in sorted(CARDS.glob("SD-*.yaml"))]


def problems(card: dict) -> list[str]:
    out = []
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    for e in jsonschema.Draft202012Validator(schema).iter_errors(card):
        out.append(f"{card.get('id', '?')}: {'/'.join(str(x) for x in e.path) or 'card'}: {e.message[:120]}")
    if out:
        return out
    if not (ROOT / card["generator"]["path"]).exists():
        out.append(f"{card['id']}: the generator {card['generator']['path']} does not exist")
    for f in card["files"]:
        if not (ROOT / f).exists():
            out.append(f"{card['id']}: the file {f} does not exist")
    for f, counts in card["rows"].items():
        path = ROOT / f
        if not path.exists():
            out.append(f"{card['id']}: the counted file {f} does not exist")
            continue
        for key, want in counts.items():
            if key.startswith("glob:"):
                got = len(list(path.glob(key[5:])))
            else:
                doc = json.loads(path.read_text(encoding="utf-8"))
                for part in key.split("."):
                    doc = doc[part]
                got = len(doc)
            if got != want:
                out.append(f"{card['id']}: {f} {key} has {got} rows, the card says {want}")
    return out


def index_text(cards: list[dict]) -> str:
    lines = ["# Synthetic datasets", "", "Every synthetic dataset in the repository has a card (schema `tools/synth/card_schema.json`). Generated by `tools/synth/publish.py`; do not edit.", "",
             "| Id | Dataset | Purpose | Generator | Use |", "|---|---|---|---|---|"]
    for c in cards:
        lines.append(f"| {c['id']} | {c['title']} | {c['purpose']} | `{c['generator']['path']}` | {c['use'].replace('_', ' ')} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    cards = load_cards()
    found = [p for c in cards for p in problems(c)]
    ids = [c.get("id") for c in cards]
    if len(ids) != len(set(ids)):
        found.append("two cards share an id")
    text = index_text(cards) if not found else ""
    if "--check" in argv:
        if not found and (not INDEX.exists() or INDEX.read_text(encoding="utf-8") != text):
            found.append("docs/research/datasets/synthetic/README.md is out of date: run tools/synth/publish.py")
        for p in found:
            print("FAIL", p)
        print(f"synthetic dataset cards: {len(cards)} cards, " + ("OK" if not found else f"{len(found)} problem(s)"))
        return 1 if found else 0
    if found:
        for p in found:
            print("REFUSED", p)
        return 1
    INDEX.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {INDEX.relative_to(ROOT).as_posix()} ({len(cards)} cards)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
