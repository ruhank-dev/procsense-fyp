"""Writes docs/research/act_benchmark.md from the committed result files: `uv run --project tools tools/bench/act_benchmark_report.py [--check]` (ADR-0020).

Reads reports/ai/act-benchmark-dev.json (development split; the status detector was trained on it, so its numbers there are fitted), reports/ai/act-benchmark.json (frozen test split, scored once) and reports/ai/act-benchmark-test2.json (second frozen split, scored once, written after the
first had been scored). Every number on the page comes from those files. Synthetic, labelled by construction, one author family: not independent.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
ROOT = Path(__file__).resolve().parents[2]
R = ROOT / "reports" / "ai"
OUT = ROOT / "docs" / "research" / "act_benchmark.md"
NAMES = {"A_rules": "A. Rules only", "B_retrieval_plus_status": "B. Embedding head + status detector", "C_model_validated": "C. Qwen 4B + validation (no rules)", "C2_rules_then_model": "C2. Rules, then Qwen 4B",
         "E_existing_gate": "E. Existing gate (hybrid head + TF-IDF head + guards)", "F_existing_gate_plus_status": "F. E + status detector"}


def table(d: dict) -> list[str]:
    L = ["| Approach | Critical false credit | Non-assertive credited | Legitimate recall | Credited precision | Latency p50 / p95 (ms) | Model calls |", "|---|---|---|---|---|---|---|"]
    for k, v in d["approaches"].items():
        t = v["totals"]
        L.append(f"| {NAMES.get(k, k)} | {t['critical_false_credit']} / {t['critical_rows']} | {t['non_assertive_false_credit']} / {t['non_assertive_rows']} | {t['legitimate_recall']:.3f} ({t['legitimate_credited']} / {t['legitimate_rows']}) | "
                 f"{t['credited_precision'] if t['credited_precision'] is not None else '-'} ({t['credited_total']} credited) | {v['latency_ms']['median']} / {v['latency_ms']['p95']} | {v['model_calls']} |")
    return L


def by_category(d: dict) -> list[str]:
    cats = sorted({c for v in d["approaches"].values() for c in v["categories"]})
    L = ["| Category (credit is wrong unless marked recall) | " + " | ".join(NAMES.get(k, k).split(".")[0] for k in d["approaches"]) + " |", "|---|" + "---|" * len(d["approaches"])]
    for c in cats:
        cells = []
        for v in d["approaches"].values():
            x = v["categories"].get(c)
            cells.append("-" if not x else (f"recall {x['recall']:.2f}" if "recall" in x else f"{x['false_credit']} / {x['n']}"))
        L.append(f"| {c} | " + " | ".join(cells) + " |")
    return L


def render() -> str:
    dev = json.loads((R / "act-benchmark-dev.json").read_text(encoding="utf-8"))
    parts = [("test", "Frozen test split, scored once (488 sentences)", "act-benchmark.json"), ("test2", "Second frozen split, written after the first had been scored and scored once after the assertion patterns were widened (488 sentences)", "act-benchmark-test2.json")]
    L = ["# The ProcSense act benchmark: five ways to recognise a communication act", "",
         "_Generated by `tools/bench/act_benchmark_report.py` from `reports/ai/act-benchmark*.json`; do not edit by hand. SYNTHETIC: the sentences are made from seed families and wrapper templates by `tools/bench/build_act_dataset.py`, the label of each follows from the construction, and nobody annotated them; the author is the builder's language model. "
         "Nothing here is independent validation. Decision: [ADR-0020](../decisions/ADR-0020-act-recognition-architecture.md)._", "",
         "Splits are by seed family and by wrapper template: a test sentence shares no family, no wording and no wrapper with a development sentence (checked at build time and in CI). Critical rows must never be credited; negated, intended, hypothetical, reported, other-actor and broken-off rows must never be credited; paraphrase and speech-recognition-error rows should be credited under the right act (recall). "
         "The status detector and the TF-IDF-based parts were trained or tuned on development only. Approach D (SetFit) was not run: see ADR-0020.", ""]
    L += ["## Development split (the status detector was trained on it: its numbers here are fitted, not evidence)", ""] + table(dev) + [""]
    for key, title, fname in parts:
        p = R / fname
        if not p.exists():
            continue
        d = json.loads(p.read_text(encoding="utf-8"))
        L += [f"## {title}", ""] + table(d) + ["", "By category:", ""] + by_category(d) + ["", f"Resident models during the run: {d.get('ollama_resident_models')}; Python process {d.get('python_rss_mb')} MB.", ""]
    return "\n".join(L) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("act benchmark page " + ("current" if ok else "OUT OF DATE: run tools/bench/act_benchmark_report.py"))
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
