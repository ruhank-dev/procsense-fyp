"""Generates docs/research/unsafe_speech_safety.md from the committed result files (p1-ai-language-s16, ADR-0023): `tools/.venv/Scripts/python.exe tools/bench/unsafe_speech_report.py [--check]`.
Inputs: tests/safety_challenge/{manifest,taxonomy}.json, reports/ai/safety/{baseline-4a2ed00,s16}-{dev,challenge,final}.json, reports/ai/safety/challenge-first-look.json, reports/ai/safety/mutation-service.json. Nothing is computed here that a result file does not hold;
the page is regenerated, never hand-edited (a test compares it with this output). Everything on it is SYNTHETIC and builder-written, with provisional labels; none of it is independent validation."""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
ROOT = Path(__file__).resolve().parents[2]
R = ROOT / "reports" / "ai" / "safety"
OUT = ROOT / "docs" / "research" / "unsafe_speech_safety.md"
SPLITS = ("dev", "challenge", "final")
NAMES = (("baseline-4a2ed00", "unchanged 4a2ed00"), ("s16", "candidate (this work)"))


def load(name, split):
    f = R / f"{name}-{split}.json"
    return json.loads(f.read_text(encoding="utf-8")) if f.exists() else None


def pct(k, n):
    return f"{100 * k / n:.1f}%" if n else "n/a"


def ci(c):
    return f"{100 * c[0]:.1f} to {100 * c[1]:.1f}%"


def build() -> str:
    man = json.loads((ROOT / "tests" / "safety_challenge" / "manifest.json").read_text(encoding="utf-8"))
    tax = json.loads((ROOT / "tests" / "safety_challenge" / "taxonomy.json").read_text(encoding="utf-8"))["categories"]
    first = json.loads((R / "challenge-first-look.json").read_text(encoding="utf-8"))
    mut = json.loads((R / "mutation-service.json").read_text(encoding="utf-8"))["mutants"] if (R / "mutation-service.json").exists() else []
    L: list[str] = []
    a = L.append
    a("# Unsafe-speech safety evaluation (generated)\n")
    a("> Generated by `tools/bench/unsafe_speech_report.py` from the committed result files; do not edit. **Synthetic, builder-written sentences with provisional labels: none of this is independent validation** (EX-01 and DT-231/DT-232 stay open; `speech_interpretation` stays OFF). "
      "Decisions and their reasons: ADR-0023; the layers and their gaps: `safety_layers_audit.md`; the review protocol: `docs/testing/safety_challenge_review.md`.\n")
    a("## 1. What was evaluated\n")
    a("Every row is built from an approved-style seed family by one transformation template (`tools/bench/safety_seeds.py`, `metamorph.py`); each row records its seed, its template and the outcome the construction implies. "
      "`credit_allowed` = a performed, non-critical act in its window (the system may offer it); `no_credit` = speech that must never become credited evidence; `ambiguous_review` = the construction does not settle the label (excluded from pass or fail, listed for a person). "
      f"Seed families and templates are disjoint across the three splits (crossing: {len(man['leakage']['seed_families_crossing_splits'])} families, {len(man['leakage']['templates_crossing_splits'])} templates); {man['dropped_near_duplicates_of_action_bench']} generated rows that were near-copies (word overlap 0.8 or more) of a `tests/action_bench_v1` sentence or of a development sentence were dropped.\n")
    a("| split | rows | credit_allowed | no_credit | ambiguous_review | role |")
    a("|---|---|---|---|---|---|")
    role = {"dev": "development: the implementation was changed on its failures", "challenge": "first look recorded in section 4, then used for development (no longer independent evidence)", "final": "untouched by any change; each configuration scored once (the candidate was frozen first, then scored)"}
    for sp in SPLITS:
        c = man["per_split"][sp]
        a(f"| {sp} | {sum(c.values())} | {c.get('credit_allowed', 0)} | {c.get('no_credit', 0)} | {c.get('ambiguous_review', 0)} | {role[sp]} |")
    a(f"\nReview status: {man['review'].get('PENDING_HUMAN_REVIEW', 0)} rows are PENDING_HUMAN_REVIEW (every ambiguous or clinically relevant row), {man['review'].get('AUTO_PROVISIONAL', 0)} AUTO_PROVISIONAL. No person has labelled any of them.\n")
    a("## 2. Baseline against candidate, identical rows\n")
    a("`unsafe credit` = a must-not-credit row for which the ENGINE's evidence store accepted evidence in some view (own context or the most permissive context). The interval is the Wilson 95 percent interval; **zero on a finite synthetic set is not zero real-world risk**. "
      "`legitimate` = performed rows credited under the right act. Both configurations were run by `tools/bench/safety_eval.py` on the same rows, the same embeddings and the same engine build.\n")
    a("| split | configuration | unsafe credit | rate (95% CI) | critical | out of window | legitimate credited | credited precision | clarify / abstain / menu on legitimate | errors |")
    a("|---|---|---|---|---|---|---|---|---|---|")
    for sp in SPLITS:
        for n, label in NAMES:
            o = load(n, sp)
            if o is None:
                a(f"| {sp} | {label} | not scored | | | | | | | |")
                continue
            u, lg, pr = o["unsafe_credit"], o["legitimate"], o["credited_precision"]
            d = o["decisions"]["legitimate"]
            a(f"| {sp} | {label} | {u['credited']}/{u['of']} | {pct(u['credited'], u['of'])} ({ci(u['wilson95'])}) | {o['critical']['credited']}/{o['critical']['of']} | {o['out_of_window']['credited']}/{o['out_of_window']['of']} | {lg['credited_right_act']}/{lg['of']} ({pct(lg['credited_right_act'], lg['of'])}) | {pr['right']}/{pr['credited']} | {d.get('CLARIFY', 0)} / {d.get('ABSTAIN', 0)} / {d.get('MENU', 0)} | {o['errors']} |")
    fin = load("s16", "final")
    fb = load("baseline-4a2ed00", "final")
    if fin and fb:
        a(f"\n**The final split is the generalisation figure** (no change was made after, or because of, looking at it; each configuration was scored once): the unchanged implementation credited {fb['unsafe_credit']['credited']} of {fb['unsafe_credit']['of']} must-not-credit rows ({pct(fb['unsafe_credit']['credited'], fb['unsafe_credit']['of'])}), the candidate {fin['unsafe_credit']['credited']} of {fin['unsafe_credit']['of']} ({pct(fin['unsafe_credit']['credited'], fin['unsafe_credit']['of'])}, 95% CI {ci(fin['unsafe_credit']['wilson95'])}). "
          "It is NOT zero, and the same author wrote the seeds and the templates of all three splits, so this is an optimistic estimate of behaviour on speech nobody on the build side wrote. The development and challenge zeros are not generalisation evidence: those splits were used to change the code. "
          "(The hash of `assertion.py` recorded at the final scoring differs from the committed file because comment lines were edited afterwards; the committed code reproduces all 897 recorded results identically, `reports/ai/safety/s16-final-reproduction.json`.)")
    a("\nLegitimate recall did not change on any split: the work removed unsafe credit and left every legitimate credit in place (and the benchmark `tests/action_bench_v1` gives identical figures, 95/140, 76/140 and 79/140 on dev, test and test2). "
      "Median per-row latency is under 15 ms in both configurations (embeddings are cached; the rules add microseconds).\n")
    a("### Session pairs (duplicates)\n")
    a("The second utterance of a pair is run with the first already credited (`in_window`) and with the session context left stale (`engine_backstop`: only the engine's own duplicate rules remain).\n")
    a("| split | configuration | pairs not applicable (the first earned nothing) | credited through a stale context |")
    a("|---|---|---|---|")
    for sp in SPLITS:
        for n, label in NAMES:
            o = load(n, sp)
            if o:
                a(f"| {sp} | {label} | {o['session_pairs_not_applicable']} | {o['engine_backstop_credit']['credited']}/{o['engine_backstop_credit']['of']} |")
    a("\n## 3. By category (credited rows / rows)\n")
    cats = sorted({c for sp in SPLITS for n, _ in NAMES if (o := load(n, sp)) for c in o["by_category"]})
    a("| category | expected | dev 4a2ed00 | dev candidate | challenge 4a2ed00 | challenge candidate | final 4a2ed00 | final candidate |")
    a("|---|---|---|---|---|---|---|---|")
    for c in cats:
        cells, exp = [], ""
        for sp in SPLITS:
            for n, _ in NAMES:
                o = load(n, sp)
                v = o["by_category"].get(c) if o else None
                if v is None:
                    cells.append("-" if o else "not scored")
                    continue
                exp = v["expected"]
                cells.append(f"{v.get('credited_right_act', v.get('credited', 0))}/{v['rows']}")
        a(f"| {c} | {exp} | " + " | ".join(cells) + " |")
    a("\nFor `no_credit` categories a credit is a failure; for `credit_allowed` categories the figure is recall; for `ambiguous_review` categories it is only reported (an ASR error that drops the negation, `asr_negation_lost`, cannot be separated from a true statement by any text rule).\n")
    a("### Combinations by template (credited / rows)\n")
    a("| split | configuration | " + " | ".join(sorted({k for sp in SPLITS for n, _ in NAMES if (o := load(n, sp)) for k in o["combinations_by_template"]}, key=lambda s: (len(s), s))) + " |")
    keys = sorted({k for sp in SPLITS for n, _ in NAMES if (o := load(n, sp)) for k in o["combinations_by_template"]}, key=lambda s: (len(s), s))
    a("|---|---|" + "---|" * len(keys))
    for sp in SPLITS:
        for n, label in NAMES:
            o = load(n, sp)
            if o:
                a(f"| {sp} | {label} | " + " | ".join(f"{o['combinations_by_template'].get(k, {}).get('credited', '-')}/{o['combinations_by_template'].get(k, {}).get('of', '-')}" if k in o["combinations_by_template"] else "-" for k in keys) + " |")
    a("\n## 4. Does fixing the development failures generalise? The first look at the challenge split\n")
    a(first["note"] + "\n")
    a("| step | unsafe credit on the challenge split | legitimate credited |")
    a("|---|---|---|")
    for s in first["steps"]:
        a(f"| {s['step']} | {s['unsafe_credit']} | {s['legitimate']} |")
    a("\nThe development-only changes removed 99 percent of the unsafe credits on development but about 38 percent on the challenge split: the first-pass patterns were too close to the development wordings. The remaining mechanisms were then generalised (the challenge split is development from that point; its final figures in section 2 are therefore NOT independent). "
      "The final split was untouched during all of this; whether the generalised patterns hold on it is shown in section 2 (scored once).\n")
    a("## 5. Representative remaining and fixed failures\n")
    for sp in ("dev", "challenge"):
        o = load("baseline-4a2ed00", sp)
        if o:
            a(f"**{sp}, credited by the unchanged 4a2ed00 and refused by the candidate (examples):**\n")
            seen = set()
            for f in o["failures"]:
                if f["category"] in seen:
                    continue
                seen.add(f["category"])
                a(f"* `{f['category']}` ({f['template']}): \"{f['text']}\"")
                if len(seen) >= 12:
                    break
            a("")
    fin = load("s16", "final")
    if fin and fin["failures"]:
        a("**Remaining failures on the final split (candidate; the split was scored once and NOT used to change anything, so these are known gaps, not fixed ones):**\n")
        for f in fin["failures"]:
            a(f"* `{f['category']}` ({f['template']}): \"{f['text']}\"")
        a("")
    a("**False-rejection causes of legitimate speech (all unchanged by this work):**\n")
    for sp in ("dev", "challenge"):
        o = load("s16", sp)
        if o:
            a(f"* {sp}: " + ", ".join(f"`{k}` {v}" for k, v in o["false_rejection_reasons"].items()) + f" (legitimate rows not credited under the right act: {o['legitimate']['of'] - o['legitimate']['credited_right_act']} of {o['legitimate']['of']})")
    a("\n`CRITICAL_MASS` is the head's critical-mass cap (0.05, deliberately not changed here); `GATE_NOT_CREDITED` is the per-act threshold or an act confusion; `NOT_PERFORMED` is the assertion layer refusing a performed sentence (the three development rows are the narration \"I'll examine your tummy in a moment\", flagged as an intention because \"in a moment\" is a delay marker: the limit of a layer that does not know the act).\n")
    a("## 6. Mutation tests: disabling each guard\n")
    if mut:
        a("Each guard was disabled in a copy of the code (`tools/ci/mutation_safety.py`) and the scenarios of `tools/ci/safety_scenarios.py` re-run: the decision of the interpretation path AND the verdict of the engine's evidence store. KILLED = an outcome changed. "
          "A double mutant removes every service copy of one barrier; the engine verdict then shows what is left.\n")
        a("| mutant | guard disabled | killed | engine verdict after the mutation (a number = how many rows of that group of sentences the engine accepted) |")
        a("|---|---|---|---|")
        for m in mut:
            ev = m.get("engine_verdicts")
            a(f"| `{m['mutant']}` | {m['guard']} | {'yes' if m['killed'] and not m['missing'] else 'NO'} | " + (", ".join(f"{k.split('_')[0]}: {v}" for k, v in ev.items()) if ev else "-") + " |")
        k = sum(1 for m in mut if m["killed"] and not m["missing"])
        a(f"\n{k} of {len(mut)} mutants killed. Reading: when the critical-mass cap's two copies are removed, 8 of the 9 sentences only the cap holds back are ACCEPTED by the engine; when the assertion layer's two uses are removed, 34 of 84 non-performed counterexamples are accepted; a critical act and an out-of-window act are refused by the engine's own checks even with every service guard gone, and accepted only when an engine check is removed too.\n")
    a("## 7. What this does and does not establish\n")
    a("* **Measured:** counts above, on the rows above, by the engine's own evidence store; the committed raw predictions in `reports/ai/safety/*-raw.json` let every number be recomputed.\n"
      "* **Estimated only:** nothing here estimates real-world rates. The seeds and the templates were written by one author (the builder, a language model), the labels follow from the construction, and the development rows were used to change the code.\n"
      "* **Not established:** independent validation (no human has labelled these rows; EX-01), clinical acceptance, headset behaviour (DC-08, DC-09, Sannan), real learner speech, real recogniser output beyond the small noise templates, and any claim that unsafe speech is now safe. "
      "A recogniser that drops a negation (`asr_negation_lost`) produces a transcript no text rule can refuse; the only defences are recogniser confidence, an audio-level check, or the verified action itself.\n")
    a("## 8. Taxonomy coverage\n")
    a("| category | group | expected | safeguards | generated |")
    a("|---|---|---|---|---|")
    for c in tax:
        a(f"| `{c['id']}` | {c['group']} | {c['expected']} | {', '.join(c['safeguards']) or '-'} | {'yes' if c['generated'] else 'mutation scenarios'} |")
    a("\nSafeguard ids are those of `docs/research/safety_layers_audit.md`; the residual risks and the tests for each category are in `tests/safety_challenge/taxonomy.json`.\n")
    return "\n".join(L) + "\n"


def main(argv):
    text = build()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/research/unsafe_speech_safety.md is out of date; run tools/bench/unsafe_speech_report.py")
            return 1
        print("unsafe_speech_safety.md is current")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
