"""A third labeller of a different size, as a cross-model check of the synthetic classifier sets: `uv run --project tools tools/bench/cross_judge.py run|report`.

    run [--set v2dev|v2test|v3test ...] [--limit N]   label the sentences blind with qwen3.5:9b (J3: the J1 prompt and rubric, temperature 0); resumable; writes <set folder>/cross_judge/J3_<split>.jsonl
    report                                             agreement of J3 with the final label of each set and with the judges J1 and J2, the labels it disagrees on, and the rows to read; writes
                                                       reports/ai/classifier-cross-judge.json and docs/research/classifier_benchmark/cross_judge_disagreements.md

Who did what, for every row of these sets (also in the report): the SENTENCE was written by the builder's language model in a simulated author profile; the LABEL is that author's intent, checked blind by J1 and J2
(qwen3.5:4b, two configurations), settled by the builder's language model when both judges disagreed with the intent; J3 (qwen3.5:9b) is the cross-model check added here and is NOT used to change any label, because a
change would unfreeze a set that was scored. No person wrote, labelled or reviewed any row. J3 is from the same model family as J1 and J2, so agreement is not independence; disagreement is a list of rows a person should read.
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
for sub in ("server", "tools/bench"):
    sys.path.insert(0, str(ROOT / sub))
import synthetic2 as S2  # noqa: E402

MODEL = "qwen3.5:9b-q4_K_M"
V2, V3 = ROOT / "tests" / "classifier_synthetic_v2", ROOT / "tests" / "classifier_synthetic_v3"
SETS = {"v2dev": (V2, "dev"), "v2test": (V2, "test"), "v3test": (V3, "test")}
REPORT = ROOT / "reports" / "ai" / "classifier-cross-judge.json"
DOC = ROOT / "docs" / "research" / "classifier_benchmark" / "cross_judge_disagreements.md"


def rows_of(folder: Path, split: str) -> list[dict]:
    return [json.loads(line) for line in (folder / f"{split}.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]


def run(names: list[str], limit: int) -> None:
    from llm import client as L
    S2.OUT = V2                                                  # the rubric of the judges (v3 uses the same words)
    system, schema, options = S2.judge_prompt("J1")
    client = L.OllamaClient()
    for name in names:
        folder, split = SETS[name]
        data = rows_of(folder, split)
        path = folder / "cross_judge" / f"J3_{split}.jsonl"
        path.parent.mkdir(exist_ok=True)
        done = {json.loads(line)["id"] for line in path.read_text(encoding="utf-8").splitlines() if line.strip()} if path.exists() else set()
        todo = [r for r in data if r["id"] not in done][: limit or None]
        t0 = time.monotonic()
        with path.open("a", encoding="utf-8", newline="\n") as f:
            for n, r in enumerate(todo, 1):
                rep = client.chat(MODEL, system, f"Sentence: {r['text']}", schema=schema, think=False, timeout=180, num_predict=60, options=options)
                act = conf = None
                if rep.ok:
                    try:
                        v = json.loads(rep.text)
                        act, conf = v["act"], float(v["confidence"])
                    except (ValueError, KeyError):
                        pass
                f.write(json.dumps({"id": r["id"], "judge": "J3", "model": MODEL, "act": act, "confidence": conf, "ms": rep.latency_ms}, sort_keys=True) + "\n")
                f.flush()
                if n % 50 == 0:
                    print(f"  {name}: {n}/{len(todo)} in {round(time.monotonic() - t0)} s", flush=True)


def load(path: Path) -> dict[str, dict]:
    return {json.loads(line)["id"]: json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()} if path.exists() else {}


def report() -> int:
    out: dict = {"model": MODEL, "synthetic": True, "independent": False, "same_family_as_judges_1_and_2": True, "sets": {}}
    lines = ["# Cross-model check of the synthetic classifier sets (J3, qwen3.5:9b)", "",
             "Generated by `tools/bench/cross_judge.py report`. Synthetic and AI-judged: J3 is the same model family as the first two judges, so agreement is not independence. No label was changed because of J3 (the sets are frozen and were scored). "
             "The rows below are the ones a person should read first.", ""]
    for name, (folder, split) in SETS.items():
        rows = rows_of(folder, split)
        j3 = load(folder / "cross_judge" / f"J3_{split}.jsonl")
        if len(j3) < len(rows):
            out["sets"][name] = {"rows": len(rows), "labelled_by_j3": len(j3), "status": "incomplete"}
            continue
        j1, j2 = load(folder / "judgements" / f"J1_{split}.jsonl"), load(folder / "judgements" / f"J2_{split}.jsonl")
        agree = sum(j3[r["id"]]["act"] == r["act"] for r in rows)
        with_j1 = sum(j3[r["id"]]["act"] == j1[r["id"]]["act"] for r in rows if r["id"] in j1)
        with_j2 = sum(j3[r["id"]]["act"] == j2[r["id"]]["act"] for r in rows if r["id"] in j2)
        crit = {a["id"] for a in S2.DS.taxonomy() if a.get("critical")}
        dis = [r for r in rows if j3[r["id"]]["act"] != r["act"]]
        pairs: dict[str, int] = {}
        for r in dis:
            key = f"{r['act']} -> {j3[r['id']]['act']}"
            pairs[key] = pairs.get(key, 0) + 1
        crit_dis = [r for r in dis if r["act"] in crit or j3[r["id"]]["act"] in crit]
        out["sets"][name] = {"rows": len(rows), "agreement_with_final_label": round(agree / len(rows), 3), "agreement_with_j1": round(with_j1 / len(j1), 3) if j1 else None,
                             "agreement_with_j2": round(with_j2 / len(j2), 3) if j2 else None, "disagreements": len(dis), "critical_involved": len(crit_dis),
                             "top_confusions": dict(sorted(pairs.items(), key=lambda kv: -kv[1])[:10]), "latency_ms_median": sorted(v["ms"] for v in j3.values())[len(j3) // 2]}
        lines += [f"## {name}: {len(dis)} of {len(rows)} rows where J3 disagrees with the final label ({len(crit_dis)} involve a critical act)", "",
                  "| id | sentence | final label | J3 | judge_status |", "|---|---|---|---|---|"]
        lines += [f"| {r['id']} | {r['text'].replace('|', '/')} | {r['act']} | {j3[r['id']]['act']} | {r.get('judge_status', '')} |" for r in crit_dis[:60]]
        lines.append("")
    REPORT.write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8", newline="\n")
    DOC.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps(out, indent=1))
    return 0


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__)
        return 2
    if argv[0] == "run":
        names = [argv[i + 1] for i, x in enumerate(argv) if x == "--set"] or list(SETS)
        run(names, int(argv[argv.index("--limit") + 1]) if "--limit" in argv else 0)
        return 0
    return report()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
