"""The classifier comparison page, generated from the committed result files: `uv run --project tools tools/bench/classifier_report.py [--check]` -> docs/research/classifier_benchmark/comparison.md.

One page that puts TF-IDF + logistic regression, sentence embeddings + logistic regression and the Qwen 3.5 4B zero-shot classifier side by side on the SAME frozen split (the v2 test split, scored once), with per-class
precision, recall and F1, the most frequent confusions (and every confusion that involves a critical act), the cost of each (latency, memory), what happened on the fresh v3 hold-out and on the four adversarial sets,
the deterministic guard measured alone, the cross-check by a larger labeller, and a table of who or what generated, labelled, adjudicated and evaluated every sentence. Nothing here is computed from a model call:
it reads reports/ai/*.json (the predictions are stored in the benchmark result) and content/assessment/taxonomy.json. The page says in its first paragraph that all of it is synthetic and AI-judged.
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "research" / "classifier_benchmark" / "comparison.md"
REP = ROOT / "reports" / "ai"
NAMES = {"tfidf_logreg": "TF-IDF + logistic regression", "embeddings_logreg": "Embeddings (all-minilm:22m) + logistic regression", "qwen_3_5_4b": "Qwen 3.5 4B zero-shot"}


def load(name: str):
    p = REP / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def critical_acts() -> set[str]:
    tax = json.loads((ROOT / "content" / "assessment" / "taxonomy.json").read_text(encoding="utf-8"))
    return {a["id"] for a in tax["acts"] if a["critical"]}


def confusions(preds: list[dict]) -> Counter:
    return Counter((p["truth"], p["pred"]) for p in preds if p["truth"] != p["pred"])


def build() -> str:
    d = load("classifier-bench-synthetic2.json")
    crit = critical_acts()
    L = ["# Classifier comparison on the AI-judged synthetic sets (generated)", "",
         "Generated by `tools/bench/classifier_report.py` from `reports/ai`; do not edit by hand. **Everything on this page is synthetic and AI-judged: model-written sentences, labels from the author's intent checked by two configurations of one "
         "local model and settled by the same builder where both disagreed with the intent. No person wrote, labelled or reviewed a row. It is not independent human validation and says nothing about real trainee speech.** "
         "The production gate for the classifier needs the independent set and stays off.", ""]
    L += ["## Who or what did what", "", "| Role | v2 (train, dev, test) | v3 hold-out |", "|---|---|---|",
          "| Wrote the sentences | the builder's language model, in 12 simulated author profiles (6 train, 3 dev, 3 test; scenario groups never shared) | the builder's language model, 3 new profiles, 2 new scenario groups |",
          "| Label | the author's intent | the author's intent |",
          "| Checked the label, blind | qwen3.5:4b, two configurations (J1 zero-shot, temperature 0; J2 reworded rubric, shuffled label order, temperature 0.3) | the same two |",
          "| Settled rows both judges disagreed with the intent on | the builder's language model (not independent: it sided with the intent in 137 of 139 rows) | the same (45 of 46) |",
          "| Cross-check added later | qwen3.5:9b (J3), labels untouched | the same |",
          "| Evaluated | TF-IDF + LR (scikit-learn), embeddings + LR head, Qwen 3.5 4B zero-shot, each tuned on dev only; test scored once | the shipped embedding head and the plain-Python TF-IDF head |",
          "| People | none | none |", ""]
    if d:
        L += ["## v2 test split (scored once, 600 sentences)", "", "| Candidate | Macro-F1 (95% interval) | Accuracy | Credited precision | Abstained | Critical acts credited from speech | Critical said, credited under another act (as scored) | p50 / p95 per sentence |", "|---|---|---|---|---|---|---|---|"]
        lat = load("classifier-latency.json") or {}
        for k, name in NAMES.items():
            c = d["candidates"][k]
            ci = c.get("macro_f1_ci95")
            ms = lat.get(k, {})
            L.append(f"| {name} | {c['macro_f1']} ({ci[0]} to {ci[1]}) | {c['accuracy']} | {c['credited_precision']} | {c['abstained_share']} | {c['critical_acts_credited_from_speech']} | {c['critical_said_but_credited_as_other_act']} | "
                     f"{ms.get('p50_ms', 'n/a')} / {ms.get('p95_ms', 'n/a')} ms |")
        L += ["", "Paired differences in macro-F1: " + "; ".join(f"{k} {v['macro_f1_difference']:+.3f} ({v['ci95'][0]} to {v['ci95'][1]})" for k, v in d["paired_macro_f1_differences"].items()) + ".", "", "Verdict recorded with the result: " + d["verdict"], ""]
        labels = list(d["candidates"]["tfidf_logreg"]["per_class"])
        L += ["### Per class (precision / recall / F1, support, false positives)", "", "| Act | Critical | Support | " + " | ".join(NAMES.values()) + " |", "|---|---|---|" + "---|" * len(NAMES)]
        for lab in labels:
            cells = []
            for k in NAMES:
                pc = d["candidates"][k]["per_class"][lab]
                cells.append(f"{pc['precision']:.2f} / {pc['recall']:.2f} / {pc['f1']:.2f} (fp {pc['false_positives']})")
            L.append(f"| {lab} | {'yes' if lab in crit else ''} | {d['candidates']['tfidf_logreg']['per_class'][lab]['support']} | " + " | ".join(cells) + " |")
        L += ["", "### Confusions (truth -> predicted, count; the ten most frequent, then every one that involves a critical act)", ""]
        for k, name in NAMES.items():
            preds = d["candidates"][k].get("predictions")
            if not preds:
                continue
            cf = confusions(preds)
            top = ", ".join(f"{t} -> {p} {n}" for (t, p), n in cf.most_common(10))
            involved = ", ".join(f"{t} -> {p} {n}" for (t, p), n in sorted(cf.items(), key=lambda x: -x[1]) if t in crit or p in crit)
            L += [f"**{name}.** Ten most frequent: {top}.", "", f"Involving a critical act ({sum(n for (t, p), n in cf.items() if t in crit or p in crit)} sentences): {involved or 'none'}.", ""]
    h = load("classifier-holdout-v3.json")
    if h:
        L += ["## v3 fresh hold-out (300 sentences, written and judged after the v2 test was scored once)", "", "| Head | Macro-F1 | Credited precision | False credits | Critical credited from speech | Critical said, credited under another act |", "|---|---|---|---|---|---|"]
        for k, name in (("shipped_head", "Embedding head as shipped"), ("tfidf_head", "Plain-Python TF-IDF head"), ("tfidf", "TF-IDF (scikit-learn)")):
            r = h.get(k)
            if r:
                L.append(f"| {name} | {r['macro_f1']} | {r['credited_precision']} | {r['false_credits']} | {r['critical_acts_credited_from_speech']} | {r['critical_said_but_credited_as_other_act']} of {r['critical_said_total']} |")
        L.append("")
    g = load("classifier-guard-only.json")
    f = load("classifier-adversarial-fresh.json")
    a = load("classifier-adversarial.json")
    if g:
        L += ["## The deterministic guard measured alone (no classifier)", "", "| Set | Critical sentences | Caught by a cue | Residual without a cue | Credit lost on ordinary speech |", "|---|---|---|---|---|"]
        for s in g["sets"]:
            fb = f"{s['false_blocks']} of {s['ordinary_rows']}" if s["ordinary_rows"] else "n/a"
            L.append(f"| {s['set']} | {s['critical_sentences']} | {s['caught_by_a_cue']} ({s['caught_share']}) | {s['residual_no_cue']} | {fb} |")
        L += ["", g["history"], ""]
    if a and f:
        sh = a["shipped_head_with_cues_v3_and_mass_guard"]
        L += ["## Critical sentences in evasive words, full path (head, critical-mass cap, cues)", "", "| Set | Sentences | Credited under an ordinary act |", "|---|---|---|",
              f"| Tuning set (the cues of version 3 were chosen from it) | {sh['tuning']['rows']} | {sh['tuning']['credited_as_ordinary_count']} |", f"| Hold-out 1 (written before that change) | {sh['holdout']['rows']} | {sh['holdout']['credited_as_ordinary_count']} |",
              f"| Hold-out 2 (tuning evidence for the cues of version 4 once seen) | {f['holdout2']['rows']} | {f['holdout2']['credited_as_ordinary_count']} |", f"| Hold-out 3 (fresh: no cue was chosen from it) | {f['holdout3']['rows']} | {f['holdout3']['credited_as_ordinary_count']} |", ""]
    j = load("classifier-cross-judge.json")
    if j:
        L += ["## Cross-check by a larger labeller (qwen3.5:9b, labels untouched)", "", "| Set | Rows | Agreement with the final label | with J1 | with J2 | Disagreements | Involving a critical act |", "|---|---|---|---|---|---|---|"]
        for name, s in j["sets"].items():
            if s.get("status") == "incomplete":
                continue
            L.append(f"| {name} | {s['rows']} | {s['agreement_with_final_label']} | {s['agreement_with_j1']} | {s['agreement_with_j2']} | {s['disagreements']} | {s['critical_involved']} |")
        L += ["", "The rows to read first are in `cross_judge_disagreements.md`. The same model family as the first two judges: agreement is not independence.", ""]
    L += ["## What this does not show", "",
          "* Anything about real trainee speech, accents, noise or hesitation: the sentences are model-written; the recogniser-noise copies of the test sentences are the only speech-like input.",
          "* That TF-IDF is better than the embeddings: on the two synthetic sets it is equal or ahead by a margin the interval does not separate. The owner chose the embeddings; the choice is kept until the independent set exists (ADR-0013).",
          "* That the guard is complete: a list of phrases does not cover new wording (the fresh adversarial set), and the head's critical-mass cap carries the rest. The engine never credits a critical act from speech.", ""]
    return "\n".join(L)


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("classifier comparison page " + ("current" if ok else "OUT OF DATE: run tools/bench/classifier_report.py"))
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
