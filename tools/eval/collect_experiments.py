"""Collects every planned or recorded experiment of the phase READMEs into one table (p0-evaluation-performance-s09): `uv run --project tools tools/eval/collect_experiments.py [--check]`, or `task report-experiments`.

Reads each `docs/plans/p*/*/README.md` for table rows whose first cell is an experiment id (EXP-...), and writes `docs/report/experiments.md`: question, method, metric, status as the phase README states it, grouped by tier
and phase, with the count per status. Nothing is typed in by hand and no result is invented: a row whose status says `planned` is reported as planned. The report chapter is generated from this file's data only
(INSTRUCTIONS 4c). `--check` fails when the committed file differs from what the READMEs give (CI). Standard library only.
"""
from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "report" / "experiments.md"
ROW = re.compile(r"^\|\s*(EXP-[A-Z0-9-]+)\s*\|(.*)\|\s*$")


def rows() -> list[dict]:
    out = []
    for readme in sorted((ROOT / "docs" / "plans").glob("p[012]/*/README.md")):
        tier, phase = readme.parts[-3], readme.parts[-2]
        for line in readme.read_text(encoding="utf-8").splitlines():
            m = ROW.match(line)
            if not m:
                continue
            cells = [c.strip() for c in m.group(2).split("|")]
            if len(cells) < 4:
                continue
            out.append({"id": m.group(1), "tier": tier, "phase": phase, "question": cells[0], "method": cells[1], "metric": cells[2], "status": cells[3] or "planned"})
    return out


def render(data: list[dict]) -> str:
    esc = lambda s: s.replace("|", "\\|")         # noqa: E731
    status = Counter((re.findall(r"[a-z]+", r["status"].lower()) or ["planned"])[0] for r in data)
    L = ["# Experiments of the phase plans", "", "_Generated by `tools/eval/collect_experiments.py` (`task report-experiments`) from the experiment tables of the phase READMEs; do not edit by hand. The status column is copied as the README states it._", "",
         f"**{len(data)} experiments** in {len({r['phase'] for r in data})} phases. Status as written: " + ", ".join(f"{k} {v}" for k, v in sorted(status.items())) + ".", ""]
    for tier in ("p0", "p1", "p2"):
        for phase in sorted({r["phase"] for r in data if r["tier"] == tier}):
            L += [f"## {tier.upper()} / {phase}", "", "| Experiment | Question | Method | Metric and pass rule | Status |", "|---|---|---|---|---|"]
            L += [f"| {r['id']} | {esc(r['question'])} | {esc(r['method'])} | {esc(r['metric'])} | {esc(r['status'])} |" for r in data if r["phase"] == phase and r["tier"] == tier]
            L.append("")
    return "\n".join(L).rstrip() + "\n"


def main(argv: list[str]) -> int:
    text = render(rows())
    if "--check" in argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("experiments chapter " + ("current" if ok else "OUT OF DATE: run tools/eval/collect_experiments.py"))
        return 0 if ok else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
