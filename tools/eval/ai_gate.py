"""The AI evaluation suite and the feature gate (p1-ai-language-s09): `uv run --project tools tools/eval/ai_gate.py [--check]`.

Reads content/ai/thresholds.json (what each feature must show) and the committed result files in reports/ai/ and writes content/ai/features.json: for each feature PASS, FAIL or SKIPPED and whether it is enabled. A feature
is enabled only if every one of its suites passes. A suite whose result file is missing is SKIPPED, and SKIPPED NEVER PASSES (plan test T-EV3): the feature stays off. A result can be compared with a number
(`value`) or with another number in the same file (`vs`, optionally plus a margin). The service reads features.json (server/ai_features.py): a disabled feature answers with the fallback signal. `--check` fails if the
file differs from what the results give, so a result cannot change without the gate changing. The weekly run of the plan is the same command run on fresh result files; a trend is the history of this file in git.
"""
from __future__ import annotations

import json
import operator
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
THRESHOLDS = ROOT / "content" / "ai" / "thresholds.json"
RESULTS = ROOT / "reports" / "ai"
OUT = ROOT / "content" / "ai" / "features.json"
OPS = {">=": operator.ge, "<=": operator.le, "==": operator.eq, ">": operator.gt, "<": operator.lt}


def dig(doc: dict, path: str):
    for part in path.split("."):
        doc = doc[part]
    return doc


def evaluate(suite: dict, results_dir: Path = RESULTS) -> dict:
    f = results_dir / suite["file"]
    if not f.exists():
        return {"id": suite["id"], "status": "SKIPPED", "why": f"no result file {suite['file']}"}
    try:
        doc = json.loads(f.read_text(encoding="utf-8"))
        got = dig(doc, suite["path"])
        want = dig(doc, suite["vs"]) if "vs" in suite else suite["value"]
        want = want + suite.get("plus", 0.0) if isinstance(want, (int, float)) else want
    except (KeyError, ValueError, TypeError):
        return {"id": suite["id"], "status": "SKIPPED", "why": f"the result file has no {suite['path']}"}
    ok = OPS[suite["op"]](got, want)
    return {"id": suite["id"], "status": "PASS" if ok else "FAIL", "got": got, "needs": f"{suite['op']} {round(want, 4) if isinstance(want, float) else want}"}


def build(results_dir: Path = RESULTS) -> dict:
    spec = json.loads(THRESHOLDS.read_text(encoding="utf-8"))
    out = {"note": "Generated by tools/eval/ai_gate.py from content/ai/thresholds.json and reports/ai; do not edit. A feature is enabled only when every suite passes; a suite with no result is SKIPPED and never passes.", "features": {}}
    for name, feat in sorted(spec["features"].items()):
        suites = [evaluate(s, results_dir) for s in feat["suites"]]
        statuses = {s["status"] for s in suites}
        status = "PASS" if statuses == {"PASS"} else "FAIL" if "FAIL" in statuses else "SKIPPED"
        informational = bool(feat.get("informational"))             # recorded for information: it can pass or fail, but it never switches anything on
        out["features"][name] = {"label": feat["label"], "status": status, "enabled": status == "PASS" and not informational, **({"informational": True} if informational else {}), "suites": suites}
    return out


def main(argv: list[str]) -> int:
    text = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if "--check" in argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("AI feature gate: " + ("current" if ok else "out of date: run tools/eval/ai_gate.py"))
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    d = json.loads(text)["features"]
    for k, v in d.items():
        print(f"{'ON ' if v['enabled'] else 'off'} {k}: {v['status']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
