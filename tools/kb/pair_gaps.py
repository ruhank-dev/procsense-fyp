"""Where the interaction proposals (feature A4, capability A4.c2) cannot reach and why: `uv run --project tools tools/kb/pair_gaps.py [--write]` -> docs/research/kb_pair_gaps.md.

A case can carry an interaction only if the APPROVED knowledge base (content/kb/relations.json) links two of its problems to the same evidence (server/generation/plan_extras.py `interaction_candidates`). The tool counts, for the whole library, the cases that have such a pair, the cases that have two or more problems but no pair, and the cases that have a single problem (nothing to pair). For each case with two or more problems and no pair it lists
PROPOSALS for a person to approve: two problems whose authored text in the case (problem `why`, a result's comment, an examination finding) shares a content word with the same piece of evidence. A proposal is a reading aid, not a relation: nothing is written to the knowledge base, no clinical relationship is asserted, and approving one needs the same
review as every relation in the queue (EX-10).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "server"))
sys.path.insert(0, str(ROOT / "tools"))
from composer import blocks as B  # noqa: E402
from generation import plan_extras as X  # noqa: E402

OUT = ROOT / "docs" / "research" / "kb_pair_gaps.md"
STOP = set("the and with for that this from have has not are was were its into than then them their there which when what about after before still only also more less very case patient patients because while should would could must need needs may can will".split())


def words(t: str) -> set[str]:
    return {w for w in re.findall(r"[a-z]{5,}", t.lower()) if w not in STOP}


def proposals(case: dict) -> list[str]:
    ev = [(f"result {r['test']} ({r.get('comment', '')})", words(r["test"] + " " + (r.get("comment") or ""))) for r in case["results"]] + [(f"finding ({e['system']}): {e['finding']}", words(e["finding"])) for e in case["examination"]]
    out = []
    probs = case["problems"]
    for i, a in enumerate(probs):
        for b in probs[i + 1:]:
            wa, wb = words(a["label"] + " " + a.get("why", "")), words(b["label"] + " " + b.get("why", ""))
            for name, we in ev:
                shared_a, shared_b = wa & we, wb & we
                if shared_a and shared_b:
                    out.append(f"`{a['id']}` + `{b['id']}` both touch {name} (words: {', '.join(sorted(shared_a | shared_b))})")
                    break
    return out


def render() -> str:
    cases = B.load_cases()
    has = [c for c in cases if X.interaction_candidates(c)]
    single = [c for c in cases if len(c["problems"]) < 2]
    gap = [c for c in cases if not X.interaction_candidates(c) and len(c["problems"]) >= 2]
    n = len(cases)
    L = ["# Why the interaction proposals reach only part of the library", "",
         "_Generated by `tools/kb/pair_gaps.py`; do not edit by hand. A reading aid for the person who approves knowledge-base relations (EX-10); nothing here is a clinical relationship and nothing was added to the knowledge base._", "",
         f"* Cases in the library: **{n}**. With a knowledge-base pair (an interaction can be proposed): **{len(has)}** ({100 * len(has) // n} percent).",
         f"* With two or more problems but no pair: **{len(gap)}**. With a single problem, so nothing to pair: **{len(single)}**.",
         f"* **Upper bound** even if every case with two or more problems had a pair: {len(has) + len(gap)} of {n} = {100 * (len(has) + len(gap)) // n} percent, below the plan's 80 percent for A4.c2. The target cannot be reached by approving more relations alone; it needs more cases with two or more problems (P3-01).", "",
         "## Cases with two or more problems and no knowledge-base pair", "", "| Case | Problems | Proposals for review (shared authored evidence) |", "|---|---|---|"]
    for c in gap:
        pr = proposals(c)
        L.append(f"| {c['id']} | {'; '.join(p['label'] for p in c['problems'])} | {'<br>'.join(pr) if pr else 'none found in the case text'} |")
    L += ["", "## Cases with a single problem", "", ", ".join(c["id"] for c in single), ""]
    return "\n".join(L) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("kb pair gaps page " + ("current" if ok else "OUT OF DATE"))
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
