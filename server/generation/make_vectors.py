"""Writes tests/vectors/difficulty_vectors.json: histories of finished sessions with the ratings the rules must give (p1-live-scenario-generation-s01).

    uv run --project tools python server/generation/make_vectors.py            # write
    uv run --project tools python server/generation/make_vectors.py --check    # fail if the file is out of date

Both implementations of the rating rules read this file: src/ProcSense.Core/Difficulty/Difficulty.cs (tests/ProcSense.Core.Tests/DifficultyVectorTests.cs) and server/generation/objectives.py.
The histories are fixed here by hand (tiers and credits/penalties per behaviour); the expected ratings come from the Python rules, and the engine test says whether the C# rules agree.
"""
import json
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from generation import objectives as ob  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "tests" / "vectors" / "difficulty_vectors.json"
BEHAVIOURS = ["b01", "b02", "b03", "b04", "b05", "b06", "b07", "b08", "b09", "b10", "b11", "b12"]


def histories() -> list[dict]:
    rng = random.Random(2026)
    out = [
        {"name": "no sessions", "sessions": []},
        {"name": "one perfect session on a P0 case", "sessions": [{"case": "VAR-S1-A", "tier": "P0", "behaviours": {"b01": [4, 0], "b02": [2, 0]}}]},
        {"name": "one failed session on a P2 case", "sessions": [{"case": "SC-1", "tier": "P2", "behaviours": {"b01": [0, 3], "b04": [1, 2]}}]},
        {"name": "a behaviour with no items is not rated", "sessions": [{"case": "VAR-S1-A", "tier": "P0", "behaviours": {"b01": [0, 0], "b02": [3, 1]}}]},
        {"name": "three mixed sessions", "sessions": [
            {"case": "VAR-S1-A", "tier": "P0", "behaviours": {"b01": [3, 1], "b02": [1, 3], "b05": [2, 2]}},
            {"case": "VAR-S1-C", "tier": "P0", "behaviours": {"b02": [2, 2], "b05": [0, 4]}},
            {"case": "VAR-S1-K", "tier": "P1", "behaviours": {"b01": [5, 0], "b05": [1, 3], "b09": [2, 2]}}]},
    ]
    for n in range(1, 9):
        sessions = []
        for i in range(rng.randint(3, 12)):
            tier = rng.choice(["P0", "P0", "P1", "P2"])
            sessions.append({"case": f"CASE-{n}-{i}", "tier": tier, "behaviours": {b: [rng.randint(0, 5), rng.randint(0, 5)] for b in rng.sample(BEHAVIOURS, rng.randint(2, 8))}})
        out.append({"name": f"random history {n}", "sessions": sessions})
    return out


def build() -> dict:
    tables = ob.Tables.load()
    cases = []
    for h in histories():
        records = [ob.SessionRecord(s["case"], s["tier"], {b: (c, p) for b, (c, p) in s["behaviours"].items()}) for s in h["sessions"]]
        r = ob.Ratings.from_history(records, tables)
        cases.append({**h, "expected": {"sessions": r.sessions, "ratings": {b: round(r.of(b), 9) for b in sorted(r.rated)}, "times_rated": {b: r.rated[b] for b in sorted(r.rated)}, "weakest": r.weakest(3)}})
    return {"note": "Generated by server/generation/make_vectors.py. Elo ratings per behaviour (K 16, start 1000, tier offsets P0 0, P1 100, P2 200); read by the C# and the Python implementations.",
            "k": tables.k, "start": tables.start, "tier_offsets": tables.tier_offsets, "min_sessions": tables.min_sessions, "cases": cases}


def main(argv: list[str]) -> int:
    text = json.dumps(build(), indent=1, sort_keys=True) + "\n"
    if "--check" in argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8").replace("\r\n", "\n") == text
        print("PASS  difficulty vectors are current" if ok else "FAIL  tests/vectors/difficulty_vectors.json is out of date: run server/generation/make_vectors.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(OUT.parents[2]).as_posix()} ({len(build()['cases'])} histories)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
